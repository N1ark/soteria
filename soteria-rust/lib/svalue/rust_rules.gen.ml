    | (PartLen) -> (TBitVector ((Z.to_int (Rust_prims.usize_bits ()))))
    | (PartVTable) -> TThinPtr
    )

let ptr_meta_as (part : meta_part) (v : t) : t =
    (match v with
    | { kind = PtrMeta (m); _ } ->
      (match part, m with
      | ((PartLen), (MetaLen (len))) -> len
      | ((PartVTable), (MetaVTable (vtable))) -> vtable
      | (_, _) -> (Rust_prims.fail_meta part m)
      )
    | _ -> (node (PtrMetaAs (part, v)) (meta_part_ty part))
    )

let rec rebuild_blocks (v : t) (bs : (block list)) (cs : (t list)) : (block list) =
    (match bs with
    | [] -> (match cs with
            | [] -> []
            | _ -> (Rust_prims.bad_blocks v)
            )
    | ({ bvalue = bv; _ } :: rest) ->
      (match cs with
      | (value :: (o :: (s :: cs_rest))) ->
        (let value2 = (match bv with
                      | (Scalar (_)) -> (Scalar (value))
                      | (Aggregate (_, ty)) -> (Aggregate (value, ty))
                      ) in
        ({ bvalue = value2; boffset = o; bsize = s } :: (rebuild_blocks v rest cs_rest)))
      | _ -> (Rust_prims.bad_blocks v)
      )
    )

let[@inline] t_as_union (s : ty) : decl_ref =
    (match s with
    | (TUnion (adt)) -> adt
    | _ -> (Rust_prims.fail_union_ty s)
    )

let[@inline] thin_part_ty (part : ptr_part) : ty =
    (match part with
    | (PtrInner) -> (TPointer ((Z.to_int (Rust_prims.usize_bits ()))))
    | (PtrSize) -> (TBitVector ((Z.to_int (Rust_prims.usize_bits ()))))
    | (PtrAlign) -> (TBitVector ((Z.to_int (Rust_prims.usize_bits ()))))
    )

let thin_ptr_part (part : ptr_part) (v : t) : t =
    (match v with
    | { kind = ThinPtr ({ ptr = p; psize = s; palign = a; _ }); _ } ->
      (match part with
      | (PtrInner) -> p
      | (PtrSize) -> s
      | (PtrAlign) -> a
      )
    | _ -> (node (ThinPtrPart (part, v)) (thin_part_ty part))
    )

let rebuild (v : t) (cs : (t list)) : t =
    (match v with
    | { kind = Var (_); _ } ->
      (match cs with
      | [] -> v
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Bool (_); _ } ->
      (match cs with
      | [] -> v
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = BitVec (_); _ } ->
      (match cs with
      | [] -> v
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = LocLit (_); _ } ->
      (match cs with
      | [] -> v
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Float (_); _ } ->
      (match cs with
      | [] -> v
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Seq (_); _ } -> (Rust_prims.mk_seq v.ty cs)
    | { kind = Exists (bs, _); _ } ->
      (match cs with
      | (a :: []) -> (b_mk_exists bs a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((Not), _); _ } ->
      (match cs with
      | (a :: []) -> (b_not a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((FAbs), _); _ } ->
      (match cs with
      | (a :: []) -> (float_abs a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((FNeg), _); _ } ->
      (match cs with
      | (a :: []) -> (float_neg a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((FSqrt), _); _ } ->
      (match cs with
      | (a :: []) -> (float_sqrt a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((GetPtrLoc), _); _ } ->
      (match cs with
      | (a :: []) -> (ptr_loc a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((GetPtrOfs), _); _ } ->
      (match cs with
      | (a :: []) -> (ptr_ofs a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((BvOfBool (n)), _); _ } ->
      let n = Z.of_int n in
      (match cs with
      | (a :: []) -> (bv_of_bool n a)
      | _ -> (Rust_prims.bad_operands v)
      )
    | { kind = Op1 ((BvOfFloat (rm, s, n)), _); _ } ->
      let n = Z.of_int n in
      (match cs with
      | (a :: []) -> (bv_of_float rm s n a)
