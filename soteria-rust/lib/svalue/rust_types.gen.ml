and equal_op3 (a : op3) (b : op3) =
  match (a, b) with
  | Ite, Ite -> true
  | Fma, Fma -> true
  | _ -> false

and hash_op3 (a : op3) =
  match a with
  | Ite -> 0
  | Fma -> 1

and equal_opn (a : opn) (b : opn) =
  match (a, b) with
  | Distinct, Distinct -> true

and hash_opn (a : opn) =
  match a with
  | Distinct -> 0

and equal_ty (a : ty) (b : ty) =
  match (a, b) with
  | TSeq a1, TSeq b1 -> equal_ty a1 b1
  | TBool, TBool -> true
  | TBitVector a1, TBitVector b1 -> Int.equal a1 b1
  | TFloat a1, TFloat b1 -> equal_fp a1 b1
  | TLoc a1, TLoc b1 -> Int.equal a1 b1
  | TPointer a1, TPointer b1 -> Int.equal a1 b1
  | TEnum a1, TEnum b1 -> equal_decl_ref a1 b1
  | TUnion a1, TUnion b1 -> equal_decl_ref a1 b1
  | TTuple a1, TTuple b1 -> (List.equal equal_ty) a1 b1
  | TArray (a1, a2), TArray (b1, b2) -> equal_ty a1 b1 && Z.equal a2 b2
  | TThinPtr, TThinPtr -> true
  | TFullPtr, TFullPtr -> true
  | TPtrMeta, TPtrMeta -> true
  | TPolyType, TPolyType -> true
  | _ -> false

and hash_ty (a : ty) =
  match a with
  | TSeq a1 -> hash_combine (0) (hash_ty a1)
  | TBool -> 1
  | TBitVector a1 -> hash_combine (2) (a1)
  | TFloat a1 -> hash_combine (3) (hash_fp a1)
  | TLoc a1 -> hash_combine (4) (a1)
  | TPointer a1 -> hash_combine (5) (a1)
  | TEnum a1 -> hash_combine (6) (hash_decl_ref a1)
  | TUnion a1 -> hash_combine (7) (hash_decl_ref a1)
  | TTuple a1 ->
      hash_combine (8)
        ((List.fold_left (fun acc x -> hash_combine acc (hash_ty x)) 0) a1)
  | TArray (a1, a2) ->
      hash_combine (hash_combine (9) (hash_ty a1)) (Z.hash a2)
  | TThinPtr -> 10
  | TFullPtr -> 11
  | TPtrMeta -> 12
  | TPolyType -> 13

