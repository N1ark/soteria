(* The NEW stack (rules generated by Kanon, typed.ml) to the neutral AST.
   Matches the generated constructors of [Rust_types]. *)

module Ty = Soteria_rust_lib.Svalue.Typed
module R = Soteria_rust_lib.Svalue.Rust_types
module Ptr_tag = Soteria_rust_lib.Svalue.Ptr_tag
module Types = Charon.Types
module Prims = Soteria_rust_lib.Svalue.Rust_prims
open Neutral

let rec sort (s : R.ty) : Neutral.sort =
  match s with
  | R.TBool -> SBool
  | R.TBitVector n -> SBv n
  | R.TLoc n -> SLoc n
  | R.TPointer n -> SPtr n
  | R.TFloat p -> SFloat (Soteria.Bv_values.Svalue.FloatPrecision.show p)
  | R.TSeq s -> SSeq (sort s)
  | R.TEnum d -> SEnum (Neutral.decl_ref d)
  | R.TUnion d -> SUnion (Neutral.decl_ref d)
  | R.TTuple tys -> STuple (List.map sort tys)
  | R.TArray (ty, n) -> SArray (sort ty, Z.to_string n)
  | R.TThinPtr -> SThin
  | R.TFullPtr -> SFull
  | R.TPtrMeta -> SMeta
  | R.TPolyType -> SPoly

let tag_str = function None -> "*" | Some t -> Ptr_tag.show t

let part_name : R.ptr_part -> string = function
  | PtrInner -> "ptr"
  | PtrSize -> "size"
  | PtrAlign -> "align"

(* The head that the printer gives to a C operator: the head of its [pp_style]
   (the generic printer prints the head and then the operands); [Not] is "!"
   even when it is printed as a [!=] *)
let op_name (v : R.t) : string =
  match v.kind with
  | R.Op1 (R.Not, _) -> "!"
  | R.OpN _ -> "distinct"
  | _ -> (
      let head h = Fmt.str "%t" h in
      match Soteria_rust_lib.Svalue.Rust_lang.pp_style v with
      | PCall h | PCallPlain h | PIn h -> head h
      | PIte -> "ite"
      | PAtom _ | PBrackets | PSeq _ -> failwith "op_name")

let memo : (int, Neutral.t) Hashtbl.t = Hashtbl.create 1021
let reset () = Hashtbl.reset memo

(* The nodes converted, by kind (for the statistics of the test) *)
let kinds : (string, int) Hashtbl.t = Hashtbl.create 31

let count (x : Neutral.t) =
  let k = Neutral.kind_name x.n in
  Hashtbl.replace kinds k
    (1 + Option.value ~default:0 (Hashtbl.find_opt kinds k))

let to_nt : R.t -> Neutral.t =
  let rec go (v : R.t) : Neutral.t =
    match Hashtbl.find_opt memo v.tag with
    | Some x -> x
    | None ->
        let x = { s = sort v.ty; n = node v } in
        Hashtbl.add memo v.tag x;
        count x;
        x
  and node (v : R.t) : Neutral.node =
    match v.kind with
    | R.Var x -> Var (Soteria.Symex.Var.to_int x)
    | R.Bool b -> Bool b
    | R.BitVec z -> Bv (Z.to_string z)
    | R.LocLit z -> Loc (Z.to_string z)
    | R.Float f -> Flt (Z.to_string (Floatml.AnyFloat.to_z f))
    | R.Seq l -> Seq (List.map go l)
    | R.Exists (bs, b) ->
        Exists
          ( List.map (fun (x, s) -> (Soteria.Symex.Var.to_int x, sort s)) bs,
            go b )
    | R.Op1 (_, a) -> Op (op_name v, [ go a ])
    | R.Op2 (_, a, b) ->
        let a = go a in
        let b = go b in
        Op (op_name v, [ a; b ])
    | R.Op3 (_, a, b, c) ->
        let a = go a in
        let b = go b in
        let c = go c in
        Op (op_name v, [ a; b; c ])
    | R.OpN (_, l) -> Op (op_name v, List.map go l)
    | R.FullPtr (p, m) ->
        let p = go p in
        let m = go m in
        Full (p, m)
    | R.PtrMeta R.MetaUnit -> MetaUnit
    | R.PtrMeta (R.MetaLen l) -> MetaLen (go l)
    | R.PtrMeta (R.MetaVTable l) -> MetaVTable (go l)
    | R.ThinPtr { ptr; ptag; psize; palign } ->
        let ptr = go ptr in
        let size = go psize in
        let align = go palign in
        Thin (tag_str ptag, ptr, size, align)
    | R.Enum (v, vs) -> Enum (Types.VariantId.to_int v, List.map go vs)
    | R.Tuple vs -> Tuple (List.map go vs)
    | R.Array vs -> Array (List.map go (Soteria.Soteria_std.Iarray.to_list vs))
    | R.Union bs ->
        Union
          (List.map
             (fun ({ bvalue; boffset; bsize } : R.block) ->
               let v, agg =
                 match bvalue with
                 | R.Scalar v -> (go v, None)
                 | R.Aggregate (v, ty) -> (go v, Some (Neutral.rty ty))
               in
               let off = go boffset in
               let sz = go bsize in
               { v; agg; off; sz })
             bs)
    | R.PolyVal id -> Poly (Types.TypeVarId.to_int id)
    | R.ThinPtrPart (p, a) -> Thin_part (part_name p, go a)
    | R.FullPtrInner a -> Full_inner (go a)
    | R.FullPtrMeta a -> Full_meta (go a)
    | R.PtrMetaAs (R.PartLen, a) -> Meta_as ("len", go a)
    | R.PtrMetaAs (R.PartVTable, a) -> Meta_as ("vtable", go a)
    | R.Field (i, a) -> Field (i, go a)
    | R.VariantField (v, i, a) ->
        Variant_field (Types.VariantId.to_int v, i, go a)
    | R.IsVariant (v, a) -> Is_variant (Types.VariantId.to_int v, go a)
    | R.ArrayField (i, a) -> Array_field (i, go a)
  in
  go

let dump (v : R.t) : string = Neutral.show (to_nt v)
let dump_ty (s : R.ty) : string = Neutral.show_sort (sort s)
