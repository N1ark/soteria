(** Bit-vector based values, with floating point support. Suitable for low-level
    languages.

    {1 Overview}

    A value language is a hash-consed term language (booleans, bit-vectors,
    floats, pointers, sequences, quantifiers) with simplifying smart
    constructors, whose types and constructors are generated by Kanon from
    declarations and rules (see the README of this directory). The code that is
    generic over such a language is written once, as functors, over the
    generated types and a {!Kanon_fns} implementation: {!Value_lang} (the
    contract of a language), {!Eval}, {!Expr}, {!Svalue_sugar} (the untyped
    layer), assembled by {!Lang_make}. {!Typed} is the typed layer of the C
    language, with a phantom type that tracks the {e kind} of each value
    (integer, boolean, pointer, ...); it is generated by Kanon, not generic.
    {!Encoding} lowers values to SMT, {!Bv_solver} drives Z3, and {!Analyses}
    are the abstract domain analyses used along the way. {!Bv_base} has the host
    types that the generated types refer to.

    {1 The language of the C tool}

    {!Lang} is the value language of soteria-c. A tool uses its typed layer
    directly:
    {@ocaml[
    include Bv_values.Typed
    ]}

    {1 Other languages}

    A tool that needs another language (soteria-rust adds aggregates and
    pointers to the shared modules) declares it for Kanon, which also generates
    its typed interface ([ocaml-typed]), and composes the generic code over the
    generated types and its implementation [K] of {!Kanon_fns}:
    {@ocaml[
    module L = Bv_values.Lang_make.Make (Types) (K)
    ]}
    It writes its own typed layer over the generated one, as {!Typed} does. To
    discharge path conditions, feed it to a solver from {!Bv_solver}. *)

