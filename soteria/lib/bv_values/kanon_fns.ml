(** The OCaml signature of everything that the generic host code needs of a
    value language generated by Kanon: the contract between the language (WP3a:
    Kanon [fn]s in [rules/view.knl|.kn]; the shared rules; the prims and glue of
    the language) and the generic functors ({!Value_lang}, {!Eval},
    {!Svalue_sugar}, {!Expr}, {!Typed}). Layout of the signature, and where each
    item comes from:

    - the modules [Core], [Bool], [Exists], [Bitvec], [Float], [Ptr]: the
      simplifying smart constructors, the sorts and the destructors that Kanon
      generates in the module of each Kanon module; [Bv_rules] has them all,
      under the same paths ([Bv_rules.Bitvec.add]).
    - [View]: Kanon [fn]s of [rules/view.knl|.kn]. Per-node knowledge. The
      functions marked [@total] have a case for every node of the language
      (Kanon checks it); a language that adds nodes (Rust) adds its cases with
      [extend fn]. All of them are [[@no_lean]].
    - [HOST]: hand-written by the language (prims and glue, [Lang] for C).

    {b Numbers.} In the signature of a Kanon [fn], both [int] and [nat] are
    {!Z.t} in the generated OCaml; only the arguments of a constructor (and so
    of the generated sort functions [t_bitvector] and destructors) keep [nat] =
    [int]. The functions of [HOST] are not Kanon [fn]s: they take OCaml [int]
    widths, like [Lang.mk_bv].

    {b Types declared by Kanon.} The types of the view ([smt_op], [smt_sort_op],
    [range_sign], [learn_plan]) are defined once in {!View_host}, and
    re-declared in [view.knl] with [[@ocaml "View_host.X"]] (and, for the
    variants, the same constructors in the same order: Kanon generates
    [type learn_plan = View_host.learn_plan = LNone | ...], which OCaml checks),
    so that every language and the generic code see the same nominal types.
    [smt_op] has parameters:
    [type smt_op [@ocaml "(t, ty) View_host.smt_op"] [@noeq]] (verified to
    generate [and smt_op = (t, ty) View_host.smt_op]). The constructor names are
    global in Kanon, hence [Inside | Outside] and not the [Pos | Neg] of
    {!Solver_lang.S} ([Neg] is a node of [bitvec]).

    The references [svalue.ml:N], [solver_lang.ml:N], [eval.ml:N], [expr.ml:N]
    and [svalue_ast.ml:N] in the comments below are to the files of the first,
    hand-written generation of the value language, deleted in S7: see
    [git show fab3ed5:soteria/lib/bv_values/svalue.ml]. *)

open Deps

module type Kanon_fns = sig
  (** The terms and sorts of the language: [Types.t] and [Types.ty]. *)
  type t

  type ty

  (** {1 Types of the view}

      Declared in {!View_host}, shared by all languages and re-declared by
      [view.knl] (see there). *)

  type smt_op = (t, ty) View_host.smt_op
  type smt_sort_op = ty View_host.smt_sort_op

  (** {1 The generated modules}

      Generated by Kanon; the semantics is that of the rules and is not this
      file's business. The integer arguments are {!Z.t}. The destructors [as_x]
      return the arguments of the node [X] (whatever its flags: [as_lt] matches
      [Lt] signed and unsigned) and [None] for any other term. *)

  module Core : sig
    val t_seq : ty -> ty

    (** [Some s] iff the sort is [TSeq s]. *)
    val as_tseq : ty -> ty option

    val as_var : t -> Var.t option
  end

  module Bool : sig
    val t_bool : ty
    val sure_neq : t -> t -> bool
    val of_bool : bool -> t
    val and_ : t -> t -> t
    val or_ : t -> t -> t
    val not_ : t -> t
    val ite : t -> t -> t -> t
    val eq : t -> t -> t
    val eq_untyped : t -> t -> t
    val distinct : t list -> t
    val is_tbool : ty -> bool
    val as_not : t -> t option
    val as_eq : t -> (t * t) option
    val as_and : t -> (t * t) option
    val as_or : t -> (t * t) option
    val as_ite : t -> (t * t * t) option
    val as_distinct : t -> t list option
  end

  module Exists : sig
    val mk : (Var.t * ty) list -> t -> t

    (** [Some (binders, body)] for an existential. *)
    val as_exists : t -> ((Var.t * ty) list * t) option
  end

  module Bitvec : sig
    val t_bitvector : int -> ty
    val add : Bv_base.checked -> t -> t -> t
    val sub : Bv_base.checked -> t -> t -> t
    val mul : Bv_base.checked -> t -> t -> t
    val div : bool -> t -> t -> t
    val rem : bool -> t -> t -> t
    val mod_ : t -> t -> t
    val neg : bool -> t -> t
    val add_overflows : bool -> t -> t -> t
    val sub_overflows : bool -> t -> t -> t
    val mul_overflows : bool -> t -> t -> t
    val neg_overflows : t -> t
    val lt : bool -> t -> t -> t
    val leq : bool -> t -> t -> t
    val concat : t -> t -> t
    val extend_ : bool -> Z.t -> t -> t
    val extract : Z.t -> Z.t -> t -> t
    val and_ : t -> t -> t
    val or_ : t -> t -> t
    val xor : t -> t -> t
    val shl : t -> t -> t
    val lshr : t -> t -> t
    val ashr : t -> t -> t
    val not_ : t -> t
    val of_bool : Z.t -> t -> t
    val to_bool : t -> t
    val not_bool : t -> t
    val of_float : Bv_base.RoundingMode.t -> bool -> Z.t -> t -> t

    val to_float :
      Bv_base.RoundingMode.t -> bool -> Bv_base.FloatPrecision.t -> t -> t

    val to_float_raw : t -> t

    (** The index of the most significant bit that can be set *)
    val msb_of : t -> Z.t

    (** [Some n] iff the sort is exactly [TBitVector n] (not a location or a
        pointer). *)
    val as_tbitvector : ty -> int option

    (** The value of a bit-vector literal ([BitVec]; not [LocLit]), with 0 <= z
        < 2^n. *)
    val as_bitvec : t -> Z.t option

    (** The value of a location literal ([LocLit]);
        {!Svalue_sugar.S.BitVec.to_z} returns the value of either. *)
    val as_loclit : t -> Z.t option

    val as_lt : t -> (bool * t * t) option
    val as_leq : t -> (bool * t * t) option
  end

  module Float : sig
    val t_float : Bv_base.FloatPrecision.t -> ty
    val is_floatclass : Bv_base.FloatClass.t -> t -> t
    val is_negative : t -> t
    val is_positive : t -> t
    val cast : Bv_base.RoundingMode.t -> Bv_base.FloatPrecision.t -> t -> t
    val eq : t -> t -> t
    val lt : t -> t -> t
    val leq : t -> t -> t
    val add : t -> t -> t
    val sub : t -> t -> t
    val div : t -> t -> t
    val mul : t -> t -> t
    val rem : t -> t -> t
    val fmod : t -> t -> t
    val fmod_of_rem : t -> t -> t -> t
    val min : t -> t -> t
    val max : t -> t -> t
    val abs : t -> t
    val neg : t -> t
    val sqrt : t -> t
    val fma : t -> t -> t -> t
    val round : Bv_base.RoundingMode.t -> t -> t

    (** [Some p] iff the sort is [TFloat p]. *)
    val as_tfloat : ty -> Bv_base.FloatPrecision.t option

    (** The value of a float literal. *)
    val as_float : t -> F.t option
  end

  module Ptr : sig
    val t_loc : int -> ty
    val t_pointer : int -> ty
    val loc : t -> t
    val ofs : t -> t

    (** [Some (loc, ofs)] for the node [Ptr (loc, ofs)] only. *)
    val as_ptr : t -> (t * t) option
  end

  (** {1 The view}

      The functions of [view.kn], with the cases that the other modules of the
      language add. *)

  module View : sig
    (** [Some n] for [TBitVector n], [TPointer n] and [TLoc n]. *)
    val sized_ty : ty -> Z.t option

    (** A boolean, bit-vector, location or float literal. *)
    val is_literal : t -> bool

    (** [A && B && C] as the list [A; B; C], flattening nested conjunctions
        only, left to right ([Bool.split_ands], [svalue.ml:648-653]).
        Specification and test oracle: {!Value_lang} implements [split_ands]
        with {!as_and} and an [Iter.t], which allocates no list. *)
    val conjuncts : t -> t list

    (** [implies_or_contradicts q neg_q pc] ([solver_lang.ml:505-532], the draft
        is in [lib/bv_values/rules/solver.kn]). [Some true] if the path
        condition conjunct [pc] implies [q], [Some false] if it implies [neg_q]
        (the negation of [q]), [None] otherwise. Hot path: it runs for every
        slot of the path condition, and must not allocate when it returns
        [None]. *)
    val implies_or_contradicts : t -> t -> t -> bool option

    (** [as_range v = Some (x, size, (side, (lo, hi)))] iff [v] states that the
        [size]-bit variable [x] is [Inside] or [Outside] the inclusive range
        [[lo, hi]] ([solver_lang.ml:303-445], the 5 cases of the paper, plus
        [Eq] and [Not]). The draft in [solver.kn] misses cases of the old code:
        both orders of [Add] with a constant, [Eq (Var, lit)], [Lt]/[Leq] with
        the constant on the right in case 3, and the [BitVec] literals must be
        at [TBitVector size] exactly. *)
    val as_range :
      t -> (Var.t * Z.t * (View_host.range_sign * (Z.t * Z.t))) option

    (** {2 Operands and rebuilding} *)

    (** The operands of a term, left to right; [[]] for a leaf. A [Seq] has its
        elements, [Distinct] its list, [Exists] its body, [Ptr] [[loc; ofs]].
        [[@total]]. Replaces [iter_vars] ([svalue.ml:71-93]), the traversals of
        [Eval.eval] ([eval.ml:73-125]), [Subst.apply] ([expr.ml:34-130]),
        [map_operands] ([solver_lang.ml:539]), [cost] ([solver_lang.ml:555]) and
        the children of [encode_node]. *)
    val operands : t -> t list

    (** [rebuild v cs] is [v] with its operands replaced by [cs]
        ([List.length cs = List.length (operands v)]), built with the same
        operator through the smart constructor of that operator; a leaf gives
        [v]. Replaces [Eval.eval_binop/unop/triop/nop] ([eval.ml:12-71]),
        [Ptr.mk] and [SSeq.mk] where [eval] and [Subst.apply] rebuild. [Ptr] is
        rebuilt with [mk_ptr] (no simplification), [Seq] with
        [mk_seq (type_of v)]. A wrong number of operands must fail (a prim), not
        return [v]. [[@total]]; its body cannot match [(v, cs)] in a tuple with
        list patterns (Kanon: a case counts for [[@total]] only if the other
        scrutinees' patterns are irrefutable), so write
        [| Not _ -> (match cs with [a] -> b_not a | _ -> fail)]. *)
    val rebuild : t -> t list -> t

    (** Whether [Solver_lang.S.map_operands] maps over the operands of this
        term: true exactly for what was a [Unop] or a [Binop]
        ([solver_lang.ml:539-548]), i.e. every [Op1] and every [Op2] except
        [Ptr]; false for [Ptr], [Seq], [Exists], [Distinct], [Ite], [Fma] and
        leaves, and by default for the nodes of extensions (they were
        [Extension] and returned unchanged). *)
    val maps_operands : t -> bool

    (** {2 Cost and model search} *)

    (** The estimated cost of bit-blasting the term ([Solver_lang.S.cost]): the
        cost of the head ([Var] 3, [Float] 2, [Seq] 0, [Distinct] 0, [Ite] 0,
        [Exists] 100_000, [Bool], [BitVec] {e and [LocLit]} 1, the tables
        [cost_unop], [cost_binop], [cost_triop] of [solver_lang.ml:555-605] for
        the operators) plus the cost of the operands, except [Ptr] which costs 1
        and no more (the old code did not recurse, [solver_lang.ml:566]);
        [Exists] is [cost body + 100_000]. [[@total]], recursive; the extensions
        give the cost of their nodes by [extend fn] (100_000, "TODO" in the old
        code). *)
    val cost : t -> Z.t

    (** The number of values that a uniform generator of the sort draws from, if
        there is one: [2^n] for [TBitVector n] and [TLoc n], 2 for [TBool],
        [2^size p] for [TFloat p], [None] for pointers, sequences, and the sorts
        of extensions ([solver_lang.ml:607-619]). *)
    val random_bound : ty -> Z.t option

    (** [random_of_z s z] is the value of sort [s] numbered [z], for 0 <= z <
        random_bound s: [mk_loc], [mk_bv], [of_bool (z = 1)], [Float.mk_bits].
        {!Value_lang} draws [z] with [Z.random_int] except for [TBool], which
        draws [Random.bool ()] as the old code did (so that the random state
        evolves identically). *)
    val random_of_z : ty -> Z.t -> t option

    (** {2 SMT encoding} *)

    (** The SMT operator of the encoding of a term, to be applied by
        {!Value_lang} as
        [(encode_head v) ~sort_of_ty ~encode_child (operands v)]. Built by prims
        ([h_add : checked -> smt_op] ...), which contain the calls to the
        encoders of [Smt] now in [Enc] ([solver_lang.ml:192-300]): the order in
        which an operator encodes its operands and sorts is its own, and must be
        that of the old code (design 3.6.9): binary operators encode left then
        right; [Triop] and [Ptr] encode right to left (the old code applied the
        encoders as function arguments); [Exists] encodes its body, then the
        sorts of its binders; [Seq] and [Distinct] left to right. Unlike the
        draft, it is not an option, so [[@total]] is possible: the terms with no
        encoding ([Seq []]: "need type to encode empty lists") return an
        operator that fails when applied. *)
    val encode_head : t -> smt_op

    (** The encoding of a sort: [encode_sort s ~sort_of_ty (sort_operands s)]
        ([Enc.encode_ty], [solver_lang.ml:173-183]). *)
    val encode_sort : ty -> smt_sort_op

    (** The sorts that a sort is made of, left to right: [[s]] for [TSeq s],
        [[]] for the others ([TTuple tys], ... in Rust). *)
    val sort_operands : ty -> ty list

    (** {2 Learning} *)

    (** How to learn the operands of a term from its value, see
        {!View_host.learn_plan} ([expr.ml:140-198]: [Not], [BvNot], [Neg],
        [BvExtend], [BvOfBool], [Add], [Sub], [BitXor], [BvConcat], [Ptr],
        [Extension]). Default [LNone]. *)
    val learn_alts : t -> View_host.learn_plan

    (** [learn_value e i v] is the value that the [i]th operand of [e] takes
        when [e = v], if any ([None]: the learning fails). Computed on demand,
        in the order that {!View_host.learn_plan} says: the old code created the
        nodes at those moments, and their tags must not change. The old values:
        [Not]: [b_not v]; [BvNot]: [bv_not v]; [Neg]: [bv_neg false v] (the flag
        is dropped); [BvExtend (_, _, e')]: [bv_extract 0 (size e' - 1) v];
        [BvOfBool]: [v_false] if [v] is the literal 0, [v_true] for 1, [None]
        otherwise; [Add (_, e1, e2)]: operand 1 is [bv_sub v e1], operand 0 is
        [bv_sub v e2]; [Sub]: operand 1 is [bv_sub e1 v], operand 0 is
        [bv_add v e2]; [BitXor]: [bv_xor v e1] / [bv_xor v e2];
        [BvConcat (e1, e2)]: operand 1 is [bv_extract 0 (size e2 - 1) v],
        operand 0 is [bv_extract (size e2) (size e1 + size e2 - 1) v]; [Ptr]:
        [ptr_loc v] and [ptr_ofs v]; Rust [Tuple]: [field_of i v]. *)
    val learn_value : t -> Z.t -> t -> t option
  end

  (** {1 HOST: constructors that Kanon cannot express, and printing of sorts}

      Hand-written by the language (the glue; [Lang] has them for C, widths are
      OCaml [int]s). The generic code cannot build these from the generated
      constructors, which it does not see. *)

  (** The boolean constants ([Bv_prims.v_true], [v_false]). Their tags are the
      first two of the language: see design 3.6.1 (creation order). *)
  val v_true : t

  val v_false : t

  (** [mk_var x s] is the variable [x] at sort [s]. Not expressible in Kanon
      without K1 (a sort given by a [ty] expression). *)
  val mk_var : Var.t -> ty -> t

  (** [mk_bv n z] is the [n]-bit literal [z] with 0 <= z < 2^n; asserts [n > 0]
      and the range. ([svalue.ml:372]) *)
  val mk_bv : int -> Z.t -> t

  (** [mk_masked n z] is [z mod 2^n] on [n] bits. ([svalue.ml:376]) *)
  val mk_masked : int -> Z.t -> t

  (** Cached constants; created, in this order, before anything else: {!v_true},
      {!v_false}, the zeros of 1 to 256 bits, then the ones of 1 to 256 bits
      ([svalue.ml:369-393]). *)
  val bv_zero : int -> t

  val bv_one : int -> t

  (** The float literal, at sort [TFloat (precision f)]. *)
  val mk_float : F.t -> t

  (** [mk_loc n z] is the [n]-bit location literal ([LocLit]); replaces
      [BitVec z <| TLoc n] ([svalue.ml:829-831]). *)
  val mk_loc : int -> Z.t -> t

  (** [mk_ptr l o] asserts that both have the same size [n] and builds the
      pointer node [Ptr (l, o)] at [TPointer n], with no simplification
      ([svalue.ml:823-826]). *)
  val mk_ptr : t -> t -> t

  (** [mk_seq s l] is the sequence [l] at the {e sequence sort} [s] ([SSeq.mk],
      [svalue.ml:849]; the sort is needed for [[]]). *)
  val mk_seq : ty -> t list -> t

  (** Prints a sort as [ppx_deriving show] did, e.g. [(TBitVector 32)]
      ([svalue_ast.ml:248]). *)
  val pp_ty : ty Fmt.t

  (** The pretty-printer of terms, written by hand over the generated types of
      each language. *)
  val pp : t Fmt.t
end
