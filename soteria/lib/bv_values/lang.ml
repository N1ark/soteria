(** The value language of the C tool ([soteria-c]), generated by Kanon from
    [rules/lang.knl]: its types ({!Types}, [bv_types.gen.ml]), the primitives of
    its rules ({!Prims}), its simplifying smart constructors and view functions
    ({!Rules}, [bv_rules.gen.ml]), the generic host code instantiated on it
    ({!L}), and below the leaf constructors and a printer of the raw terms.

    [Typed] is the typed layer of the tool; [Svalue], [Eval] and [Expr] are the
    same modules as [Typed.Svalue], [Typed.Eval] and [Typed.Expr]. The terms are
    hash-consed in one global table, created, like the constants [v_true],
    [v_false] and the cached literals, when this module is initialised. *)

module Types = Bv_types
module Prims = Bv_prims
module Rules = Bv_rules
open Bv_types

(** {1 Sorts} *)

let t_bool = TBool
let t_bv n = TBitVector n
let t_float fp = TFloat fp
let t_f16 = TFloat F16
let t_f32 = TFloat F32
let t_f64 = TFloat F64
let t_f128 = TFloat F128
let t_loc n = TLoc n
let t_ptr n = TPointer n
let t_seq ty = TSeq ty
let size_of_ty = Prims.size_of
let equal = equal_t
let compare (a : t) (b : t) = Int.compare a.tag b.tag
let hash (a : t) = a.tag

(** {1 Leaves} *)

let v_true = Prims.v_true
let v_false = Prims.v_false
let mk_bool b = if b then v_true else v_false

(** [mk_bv n z] asserts that [z] fits in [n] bits *)
let mk_bv n z = Prims.mk_bv_int n z

let mk_masked n z = Prims.mk_masked_int n z
let bv_zero n = Prims.bv_zero_int n
let bv_one n = Prims.bv_one_int n
let mk_float f = node (Float f) (TFloat (Floatml.AnyFloat.precision f))
let mk_var v ty = node (Var v) ty
let mk_loc n z = node (LocLit z) (TLoc n)
let null_loc n = mk_loc n Z.zero

let mk_ptr (l : t) (o : t) =
  let n = Prims.size_of o.ty in
  assert (Prims.size_of l.ty = n);
  node (Op2 (Ptr, l, o)) (TPointer n)

let mk_seq ~seq_ty l = node (Seq l) seq_ty
let mk_exists = Rules.Exists.mk

(** {1 Printing: s-expressions} *)

let rec pp_ty ft = function
  | TBool -> Fmt.string ft "bool"
  | TBitVector n -> Fmt.pf ft "bv%d" n
  | TFloat p -> Fmt.pf ft "f%d" (Floatml.AnyFloat.size p)
  | TLoc n -> Fmt.pf ft "loc%d" n
  | TPointer n -> Fmt.pf ft "ptr%d" n
  | TSeq ty -> Fmt.pf ft "(seq %a)" pp_ty ty

let pp_s ft b = Fmt.string ft (if b then "s" else "u")

let pp_checked ft (c : checked) =
  Fmt.pf ft "%s%s"
    (if c.signed then "s" else "")
    (if c.unsigned then "u" else "")

let pp_rm = Bv_base.RoundingMode.pp
let pp_fc = Bv_base.FloatClass.pp
let pp_fp ft p = Fmt.pf ft "f%d" (Floatml.AnyFloat.size p)

let pp_op1 ft = function
  | Not -> Fmt.string ft "not"
  | BvOfBool n -> Fmt.pf ft "b2bv %d" n
  | BvExtract (i, j) -> Fmt.pf ft "extract %d %d" i j
  | BvExtend (s, k) -> Fmt.pf ft "extend %a %d" pp_s s k
  | BvNot -> Fmt.string ft "bvnot"
  | Neg c -> Fmt.pf ft "neg %b" c
  | BvOfFloat (rm, s, n) -> Fmt.pf ft "f2bv %a %a %d" pp_rm rm pp_s s n
  | FloatOfBv (rm, s, p) -> Fmt.pf ft "bv2f %a %a %a" pp_rm rm pp_s s pp_fp p
  | FloatOfBvRaw p -> Fmt.pf ft "bv2f_raw %a" pp_fp p
  | FloatOfFloat (rm, p) -> Fmt.pf ft "f2f %a %a" pp_rm rm pp_fp p
  | FAbs -> Fmt.string ft "fabs"
  | FNeg -> Fmt.string ft "fneg"
  | FSqrt -> Fmt.string ft "fsqrt"
  | FIs fc -> Fmt.pf ft "fis %a" pp_fc fc
  | FIsNeg -> Fmt.string ft "fisneg"
  | FIsPos -> Fmt.string ft "fispos"
  | FRound rm -> Fmt.pf ft "fround %a" pp_rm rm
  | GetPtrLoc -> Fmt.string ft "loc"
  | GetPtrOfs -> Fmt.string ft "ofs"

let pp_op2 ft = function
  | And -> Fmt.string ft "and"
  | Or -> Fmt.string ft "or"
  | Eq -> Fmt.string ft "eq"
  | Add c -> Fmt.pf ft "add %a" pp_checked c
  | Sub c -> Fmt.pf ft "sub %a" pp_checked c
  | Mul c -> Fmt.pf ft "mul %a" pp_checked c
  | Div s -> Fmt.pf ft "div %a" pp_s s
  | Rem s -> Fmt.pf ft "rem %a" pp_s s
  | Mod -> Fmt.string ft "mod"
  | AddOvf s -> Fmt.pf ft "add_ovf %a" pp_s s
  | SubOvf s -> Fmt.pf ft "sub_ovf %a" pp_s s
  | MulOvf s -> Fmt.pf ft "mul_ovf %a" pp_s s
  | Lt s -> Fmt.pf ft "lt %a" pp_s s
  | Leq s -> Fmt.pf ft "leq %a" pp_s s
  | BvConcat -> Fmt.string ft "concat"
  | BitAnd -> Fmt.string ft "bvand"
  | BitOr -> Fmt.string ft "bvor"
  | BitXor -> Fmt.string ft "bvxor"
  | Shl -> Fmt.string ft "shl"
  | LShr -> Fmt.string ft "lshr"
  | AShr -> Fmt.string ft "ashr"
  | FEq -> Fmt.string ft "feq"
  | FLeq -> Fmt.string ft "fleq"
  | FLt -> Fmt.string ft "flt"
  | FAdd -> Fmt.string ft "fadd"
  | FSub -> Fmt.string ft "fsub"
  | FMul -> Fmt.string ft "fmul"
  | FDiv -> Fmt.string ft "fdiv"
  | FRem -> Fmt.string ft "frem"
  | FMin -> Fmt.string ft "fmin"
  | FMax -> Fmt.string ft "fmax"
  | Ptr -> Fmt.string ft "ptr"

let pp_op3 ft = function
  | Ite -> Fmt.string ft "ite"
  | Fma -> Fmt.string ft "fma"

let pp_opn ft = function Distinct -> Fmt.string ft "distinct"

(** [pp] prints a term as an s-expression; the sort of a literal or a variable
    is printed with it. *)
let rec pp ft (t : t) =
  match t.kind with
  | Var v -> Fmt.pf ft "(var %d : %a)" (Symex.Var.to_int v) pp_ty t.ty
  | Seq l -> Fmt.pf ft "(seq %a)" (Fmt.list ~sep:Fmt.sp pp) l
  | Bool b -> Fmt.pf ft "%b" b
  | BitVec z -> Fmt.pf ft "(bv %a %a)" pp_ty t.ty Z.pp_print z
  | LocLit z -> Fmt.pf ft "(locl %a %a)" pp_ty t.ty Z.pp_print z
  | Float f -> Fmt.pf ft "(float %s)" (Floatml.AnyFloat.to_string f)
  | Exists (vs, b) ->
      let pp_b ft (v, ty) =
        Fmt.pf ft "(%d : %a)" (Symex.Var.to_int v) pp_ty ty
      in
      Fmt.pf ft "(exists (%a) %a)" (Fmt.list ~sep:Fmt.sp pp_b) vs pp b
  | Op1 (op, a) -> Fmt.pf ft "(%a %a)" pp_op1 op pp a
  | Op2 (op, a, b) -> Fmt.pf ft "(%a %a %a)" pp_op2 op pp a pp b
  | Op3 (op, a, b, c) -> Fmt.pf ft "(%a %a %a %a)" pp_op3 op pp a pp b pp c
  | OpN (op, l) -> Fmt.pf ft "(%a %a)" pp_opn op (Fmt.list ~sep:Fmt.sp pp) l

let show = Fmt.to_to_string pp

(** {1 The language} *)

(** The language as the generic host code consumes it: the generated rules and
    view functions, and the constants and builders above. *)
module K : Kanon_fns.Kanon_fns with type t = Types.t and type ty = Types.ty =
struct
  type t = Types.t
  type ty = Types.ty
  type smt_op = (t, ty) View_host.smt_op
  type smt_sort_op = ty View_host.smt_sort_op

  include Rules

  let v_true = v_true
  let v_false = v_false
  let mk_var = mk_var
  let mk_bv = mk_bv
  let mk_masked = mk_masked
  let bv_zero = bv_zero
  let bv_one = bv_one
  let mk_float = mk_float
  let mk_loc = mk_loc
  let mk_ptr = mk_ptr
  let mk_seq ty l = mk_seq ~seq_ty:ty l
  let pp_ty = Bv_pp.pp_ty
  let pp = Bv_pp.pp
end

module L = Lang_make.Make (Types) (K)

(** The view of the language for the solver ({!Solver_lang.S}). *)
module V = L.V

module Svalue = L.Svalue
module Eval = L.Eval
module Expr = L.Expr
