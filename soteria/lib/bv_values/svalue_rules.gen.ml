    (match p with
    | { Hc.node = { Svalue_ast.kind = Svalue_ast.Ptr (_, o); _ }; _ } -> o
    | _ ->
      (let n = (size p) in
      (P.node (Svalue_ast.Unop (Svalue_ast.Unop.GetPtrOfs, p)) (Svalue_ast.TBitVector ((Z.to_int n)))))
    )


