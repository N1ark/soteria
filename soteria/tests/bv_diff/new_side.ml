(** The NEW simplifier: [Bv_values.Lang], types and rule functions generated by
    the new Kanon. This file adapts it to {!Side.RAW}: the leaves
    ([Soteria.Bv_values.Lang.mk_*]), the rule functions
    ([Soteria.Bv_values.Lang.Rules.*], called as plain functions) and the
    structural view of its terms ([Bv_types.kind]: [Op1/Op2/Op3/OpN] to
    {!Tm.node}, [Op2 (Ptr, _, _)] to a pointer, [LocLit] to a location literal).
    The compositions of the public API are those of {!Side.Compose}, shared with
    nothing else on the old side (the old side goes through its own public API).
*)

open Tm
module B = Soteria.Bv_values.Lang
module T = Soteria.Bv_values.Lang.Types
module R = Soteria.Bv_values.Lang.Rules
module V = Soteria.Symex.Var

module Raw : Side.RAW with type t = T.t = struct
  type t = T.t

  let name = "Lang"
  let tag (x : t) = x.tag

  let rec sort_of_ty : T.ty -> sort = function
    | TBool -> SBool
    | TBitVector n -> SBv n
    | TFloat p -> SFloat p
    | TLoc n -> SLoc n
    | TPointer n -> SPtr n
    | TSeq t -> SSeq (sort_of_ty t)

  let rec ty_of_sort : sort -> T.ty = function
    | SBool -> TBool
    | SBv n -> TBitVector n
    | SFloat p -> TFloat p
    | SLoc n -> TLoc n
    | SPtr n -> TPointer n
    | SSeq t -> TSeq (ty_of_sort t)

  let sort_of (x : t) = sort_of_ty x.ty
  let pp (x : t) = Fmt.str "%a" B.pp x

  let node1 : T.op1 -> node = function
    | Not -> N_not
    | GetPtrLoc -> N_ptr_loc
    | GetPtrOfs -> N_ptr_ofs
    | BvOfBool n -> N_bv_of_bool n
    | BvOfFloat (rm, s, n) -> N_bv_of_float (rm, s, n)
    | FloatOfBv (rm, s, p) -> N_float_of_bv (rm, s, p)
    | FloatOfBvRaw p -> N_float_of_bv_raw p
    | FloatOfFloat (rm, p) -> N_float_of_float (rm, p)
    | BvExtract (i, j) -> N_extract (i, j)
    | BvExtend (s, k) -> N_extend (s, k)
    | BvNot -> N_bvnot
    | Neg c -> N_neg c
    | FAbs -> N_fabs
    | FNeg -> N_fneg
    | FSqrt -> N_fsqrt
    | FIs fc -> N_fis fc
    | FIsNeg -> N_fisneg
    | FIsPos -> N_fispos
    | FRound rm -> N_fround rm

  let ck (c : T.checked) = (c.signed, c.unsigned)

  (* [Ptr] is not a node of the view: see [view] *)
  let node2 : T.op2 -> node = function
    | And -> N_and
    | Or -> N_or
    | Eq -> N_eq
    | FEq -> N_feq
    | FLeq -> N_fleq
    | FLt -> N_flt
    | FAdd -> N_fadd
    | FSub -> N_fsub
    | FMul -> N_fmul
    | FDiv -> N_fdiv
    | FRem -> N_frem
    | FMin -> N_fmin
    | FMax -> N_fmax
    | Add c -> N_add (ck c)
    | Sub c -> N_sub (ck c)
    | Mul c -> N_mul (ck c)
    | Div s -> N_div s
    | Rem s -> N_rem s
    | Mod -> N_mod
    | AddOvf s -> N_addovf s
    | SubOvf s -> N_subovf s
    | MulOvf s -> N_mulovf s
    | Lt s -> N_lt s
    | Leq s -> N_leq s
    | BvConcat -> N_concat
    | BitAnd -> N_bitand
    | BitOr -> N_bitor
    | BitXor -> N_bitxor
    | Shl -> N_shl
    | LShr -> N_lshr
    | AShr -> N_ashr
    | Ptr -> failwith "node2: Ptr"

  let view (x : t) : t view =
    match x.kind with
    | Var v -> VVar (V.to_int v, sort_of x)
    | Bool b -> VBool b
    | Seq l -> VSeq l
    | Exists (bs, b) ->
        VExists (List.map (fun (v, ty) -> (V.to_int v, sort_of_ty ty)) bs, b)
    | BitVec z -> (
        match x.ty with
        | TBitVector n -> VBv (n, z)
        | _ -> failwith "BitVec literal of a non bit-vector sort")
    | LocLit z -> (
        match x.ty with
        | TLoc n -> VLoc (n, z)
        | _ -> failwith "LocLit of a non location sort")
    | Float f -> VFloat (Floatml.AnyFloat.precision f, Floatml.AnyFloat.to_z f)
    | Op1 (o, a) -> VNode (node1 o, [ a ])
    | Op2 (Ptr, l, o) -> VPtr (l, o)
    | Op2 (o, a, b) -> VNode (node2 o, [ a; b ])
    | Op3 (Ite, a, b, c) -> VNode (N_ite, [ a; b; c ])
    | Op3 (Fma, a, b, c) -> VNode (N_fma, [ a; b; c ])
    | OpN (Distinct, l) -> VNode (N_distinct, l)

  let mk_var i s = B.mk_var (V.of_int i) (ty_of_sort s)
  let mk_bool = B.mk_bool
  let mk_bv n z = B.mk_bv n z
  let mk_loc n z = B.mk_loc n z
  let mk_float p z = B.mk_float (Floatml.AnyFloat.of_bits_z p z)
  let mk_ptr = B.mk_ptr
  let mk_seq s l = B.mk_seq ~seq_ty:(ty_of_sort s) l
  let b_and = R.b_and
  let b_or = R.b_or
  let b_not = R.b_not
  let b_ite = R.b_ite
  let sem_eq = R.sem_eq
  let sem_eq_untyped = R.sem_eq_untyped
  let b_distinct = R.b_distinct

  let b_mk_exists bs body =
    R.b_mk_exists (List.map (fun (v, s) -> (V.of_int v, ty_of_sort s)) bs) body

  let c (s, u) : T.checked = { signed = s; unsigned = u }
  let bv_add ck = R.bv_add (c ck)
  let bv_sub ck = R.bv_sub (c ck)
  let bv_mul ck = R.bv_mul (c ck)
  let bv_div = R.bv_div
  let bv_rem = R.bv_rem
  let bv_mod = R.bv_mod
  let bv_neg = R.bv_neg
  let bv_add_overflows = R.bv_add_overflows
  let bv_sub_overflows = R.bv_sub_overflows
  let bv_mul_overflows = R.bv_mul_overflows
  let bv_neg_overflows = R.bv_neg_overflows
  let bv_lt = R.bv_lt
  let bv_leq = R.bv_leq
  let bv_concat = R.bv_concat
  let bv_extend s k = R.bv_extend s (Z.of_int k)
  let bv_extract i j = R.bv_extract (Z.of_int i) (Z.of_int j)
  let bv_and = R.bv_and
  let bv_or = R.bv_or
  let bv_xor = R.bv_xor
  let bv_shl = R.bv_shl
  let bv_lshr = R.bv_lshr
  let bv_ashr = R.bv_ashr
  let bv_not = R.bv_not
  let bv_of_bool n = R.bv_of_bool (Z.of_int n)
  let bv_to_bool = R.bv_to_bool
  let bv_not_bool = R.bv_not_bool
  let bv_of_float rm s n = R.bv_of_float rm s (Z.of_int n)
  let bv_to_float = R.bv_to_float
  let bv_to_float_raw = R.bv_to_float_raw
  let float_is_floatclass = R.float_is_floatclass
  let float_is_negative = R.float_is_negative
  let float_is_positive = R.float_is_positive
  let float_cast = R.float_cast
  let float_eq = R.float_eq
  let float_lt = R.float_lt
  let float_leq = R.float_leq
  let float_add = R.float_add
  let float_sub = R.float_sub
  let float_div = R.float_div
  let float_mul = R.float_mul
  let float_rem = R.float_rem
  let float_abs = R.float_abs
  let float_neg = R.float_neg
  let float_fma = R.float_fma
  let float_fmod_of_rem = R.float_fmod_of_rem
  let float_fmod = R.float_fmod
  let float_min = R.float_min
  let float_max = R.float_max
  let float_sqrt = R.float_sqrt
  let float_round = R.float_round
  let ptr_loc = R.ptr_loc
  let ptr_ofs = R.ptr_ofs
end

module Mut = Mutate.Make (Raw)
include Side.Compose (Mut)

let available = true
let label = "Bv_values.Lang (Kanon-generated types and rules)"
