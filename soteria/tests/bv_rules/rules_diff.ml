(** Random differential tests of the rule functions of Bv_values (see
    [soteria/bvr]). For every rule function, generated by [bvr ocaml-tests], it
    draws small well-typed arguments, and checks that the result of the rule
    function refines its spec (the raw term): it is well-typed, of the same
    type, and, under random assignments of the variables where the spec is not
    poison (a checked operation that overflows), it is not poison and evaluates
    to the same literal, with {!Eval}.

    [BVR_RULE_COUNT] sets the number of well-typed draws per function,
    [BVR_RULE_SEED] the seed, and [BVR_RULE_STATS] prints how often each rule
    fired. *)

open Soteria.Bv_values
module Typed = Typed.Make (Svalue.Dummy_ext) ()
module Sv = Typed.Svalue
module Eval = Typed.Eval

(* The names that the generated code uses *)
module Svalue_ast = Svalue
module Symex = Soteria.Symex

module Cases = struct
  open Sv.R

  [%%include_file "rules_diff.gen.ml"]
end

let env_int name default =
  Option.bind (Sys.getenv_opt name) int_of_string_opt |> Option.value ~default

let count = env_int "BVR_RULE_COUNT" 500
let seed = env_int "BVR_RULE_SEED" 0
let stats = Sys.getenv_opt "BVR_RULE_STATS" <> None
let assignments = 4
let rs = Random.State.make [| seed |]
let int k = Random.State.int rs k
let chance p = Random.State.float rs 1. < p
let pick l = List.nth l (int (List.length l))

(* ------------------------------------------------------------------ *)
(* Well-typedness, following the typing of the operators in lang.bvl  *)
(* ------------------------------------------------------------------ *)

let ty_of (v : Sv.t) = v.node.ty
let ok_ty : Sv.ty -> bool = function TBitVector n -> n > 0 | _ -> true

let rec wt (x : Sv.t) : bool =
  let ty = ty_of x in
  let bv v = match ty_of v with TBitVector n -> n | _ -> -1 in
  let fp v = match ty_of v with TFloat p -> Some p | _ -> None in
  let is_bool v = ty_of v = TBool in
  let same a b = Sv.equal_ty (ty_of a) (ty_of b) in
  ok_ty ty
  &&
  match x.node.kind with
  | Var _ -> true
  | Bool _ -> ty = TBool
  | BitVec _ -> bv x > 0
  | Float f -> fp x = Some (Floatml.AnyFloat.precision f)
  | Unop (op, a) -> (
      wt a
      &&
      match op with
      | Not -> is_bool a && ty = TBool
      | BvOfBool n -> is_bool a && bv x = n
      | BvOfFloat (_, _, n) -> fp a <> None && bv x = n
      | FloatOfBv (_, _, p) -> bv a > 0 && fp x = Some p
      | FloatOfBvRaw p -> bv a = Svalue.FloatPrecision.size p && fp x = Some p
      | FloatOfFloat (_, p) -> fp a <> None && fp x = Some p
      | BvExtract (i, j) -> 0 <= i && i <= j && j < bv a && bv x = j - i + 1
      | BvExtend (_, k) -> bv a > 0 && k >= 0 && bv x = bv a + k
      | BvNot | Neg _ -> bv a > 0 && same a x
      | FAbs | FNeg | FSqrt | FRound _ -> fp a <> None && same a x
      | FIs _ | FIsNeg | FIsPos -> fp a <> None && ty = TBool
      | GetPtrLoc | GetPtrOfs -> false)
  | Binop (op, a, b) -> (
      wt a
      && wt b
      &&
      match op with
      | And | Or -> is_bool a && is_bool b && ty = TBool
      | Eq -> same a b && ty = TBool
      | FEq | FLeq | FLt -> fp a <> None && same a b && ty = TBool
      | FAdd | FSub | FMul | FDiv | FRem | FMin | FMax ->
          fp a <> None && same a b && same a x
      | Add _ | Sub _ | Mul _ | Div _ | Rem _ | Mod | BitAnd | BitOr | BitXor
      | Shl | LShr | AShr ->
          bv a > 0 && same a b && same a x
      | AddOvf _ | SubOvf _ | MulOvf _ | Lt _ | Leq _ ->
          bv a > 0 && same a b && ty = TBool
      | BvConcat -> bv a > 0 && bv b > 0 && bv x = bv a + bv b)
  | Triop (Ite, g, a, b) ->
      wt g && wt a && wt b && is_bool g && same a b && same a x
  | Triop (Fma, a, b, c) ->
      wt a && wt b && wt c && fp a <> None && same a b && same a c && same a x
  | Nop (Distinct, l) ->
      List.for_all wt l
      && (match l with [] -> true | h :: t -> List.for_all (same h) t)
      && ty = TBool
  | Ptr _ | Seq _ | Exists _ | Extension _ -> false

