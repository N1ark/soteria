(* The tests                                                          *)
(* ------------------------------------------------------------------ *)

(** The outcome of a draw; [Passed] and [Failed] name the rule that fired. *)
type outcome =
  | Rejected
  | Inconclusive
  | Passed of string
  | Failed of string * string

(** The rule functions with no well-typed draw, as pointers are not drawn. *)
let undrawn = [ "ptr_loc"; "ptr_ofs" ]

let check (t : Cases.test) =
  match t.spec () with
  | exception _ -> Rejected
  | spec when not (wt spec) -> Rejected
  | spec -> (
      (* the assertions of the function are its preconditions *)
      match t.fired () with
      | exception Assert_failure _ -> Rejected
      | fired -> (
          match t.call () with
          | exception e ->
              Failed
                ( fired,
                  Fmt.str "raises %s on %a" (Printexc.to_string e) Sv.pp spec )
          | res when not (wt res && Sv.equal_ty (ty_of res) (ty_of spec)) ->
              Failed
                (fired, Fmt.str "%a is ill-typed, for %a" Sv.pp res Sv.pp spec)
          | res ->
              let rec go i conclusive =
                if i = assignments then
                  if conclusive then Passed fired else Inconclusive
                else
                  let env = Hashtbl.create 8 in
                  let fail msg =
                    Failed
                      ( fired,
                        Fmt.str "@[<v 2>%a@ simplified to %a@ %s@ under %a@]"
                          Sv.pp spec Sv.pp res msg
                          Fmt.(
                            iter_bindings ~sep:comma Hashtbl.iter
                              (pair ~sep:(any " := ") Symex.Var.pp Sv.pp))
                          env )
                  in
                  match defined env spec with
                  | Some false -> go (i + 1) conclusive
                  | None -> go (i + 1) false
                  | Some true -> (
                      let spec_v = eval env spec and res_v = eval env res in
                      match defined env res with
                      | Some false -> fail "is poison"
                      | None -> go (i + 1) false
                      | Some true ->
                          if not (is_lit spec_v && is_lit res_v) then
                            go (i + 1) (conclusive && Sv.equal spec_v res_v)
                          else if Sv.equal spec_v res_v then
                            go (i + 1) conclusive
                          else
                            fail
                              (Fmt.str "evaluates to %a instead of %a" Sv.pp
                                 res_v Sv.pp spec_v))
              in
              go 0 true))

let () =
  let failures = ref 0 in
  List.iter
    (fun (name, rules, make) ->
      let fired = Hashtbl.create 16 in
      let tested = ref 0 and inconclusive = ref 0 and shown = ref 0 in
      let attempts = ref 0 in
      while !tested < count && !attempts < 50 * count do
        incr attempts;
        let t = make (source ()) in
        match check t with
        | Rejected -> ()
        | Inconclusive ->
            incr tested;
            incr inconclusive
        | Passed r ->
            incr tested;
            Hashtbl.replace fired r
              (1 + Option.value ~default:0 (Hashtbl.find_opt fired r))
        | Failed (r, msg) ->
            incr tested;
            incr failures;
            incr shown;
            if !shown <= 3 then
              Fmt.pr "@[<v 2>FAIL %s (rule %s):@ %s@]@." name r msg
      done;
      let hits r = Option.value ~default:0 (Hashtbl.find_opt fired r) in
      if stats then
        Fmt.pr "@[<hov 2>%s: %d draws, %d inconclusive;@ %a@]@." name !tested
          !inconclusive
          Fmt.(list ~sep:sp (fun ft r -> pf ft "%s=%d" r (hits r)))
          rules;
      if !tested = 0 && not (List.mem name undrawn) then (
        incr failures;
        Fmt.pr "FAIL %s: no well-typed draw@." name))
    Cases.rule_fns;
  if stats then Fmt.pr "untested: %a@." Fmt.(list ~sep:sp string) Cases.untested;
  if !failures > 0 then exit 1
