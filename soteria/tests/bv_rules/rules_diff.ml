let eval env (v : Sv.t) =
  let eval_var _ v ty =
    match Hashtbl.find_opt env v with
    | Some x -> x
    | None ->
        let x = value ty in
        Hashtbl.replace env v x;
        x
  in
  Eval.eval ~force:true ~eval_var v

(** Whether [v] is not poison under [env], following [Bvr/Semantics.lean];
    [None] if the evaluation does not tell. *)
let rec defined env (v : Sv.t) : bool option =
  let ( &&& ) a b =
    match a with Some true -> b () | Some false -> Some false | None -> None
  in
  let lit x =
    match (eval env x).node.kind with Bool b -> Some b | _ -> None
  in
  let not_ x = Option.map not (lit x) in
  let all l =
    List.fold_left (fun acc x -> acc &&& fun () -> defined env x) (Some true) l
  in
  let parallel absorbing a b =
    let da = defined env a and db = defined env b in
    let absorbs d x = d = Some true && lit x = Some absorbing in
    if absorbs da a || absorbs db b then Some true
    else Option.bind da (fun da -> Option.map (( && ) da) db)
  in
  let checked (c : Svalue.checked) ovf a b =
    let no_ovf signed = not_ Sv.(Binop (ovf signed, a, b) <| TBool) in
    all [ a; b ] &&& fun () ->
    (if c.signed then no_ovf true else Some true) &&& fun () ->
    if c.unsigned then no_ovf false else Some true
  in
  match v.node.kind with
  | Var _ | Bool _ | BitVec _ | Float _ -> Some true
  | Binop (And, a, b) -> parallel false a b
  | Binop (Or, a, b) -> parallel true a b
  | Binop (Add c, a, b) -> checked c (fun s -> AddOvf s) a b
  | Binop (Sub c, a, b) -> checked c (fun s -> SubOvf s) a b
  | Binop (Mul c, a, b) -> checked c (fun s -> MulOvf s) a b
  | Unop (Neg true, a) ->
      let n = Sv.size_of (ty_of a) in
      let min = Sv.BitVec.mk_masked n (Z.shift_left Z.one (n - 1)) in
      defined env a &&& fun () -> not_ Sv.(Binop (Eq, a, min) <| TBool)
  | Triop (Ite, g, a, b) -> (
      defined env g &&& fun () ->
      match lit g with
      | Some g -> defined env (if g then a else b)
      | None -> None)
  | Unop (_, a) -> all [ a ]
  | Binop (_, a, b) -> all [ a; b ]
  | Triop (_, a, b, c) -> all [ a; b; c ]
  | Nop (_, l) -> all l
  | Ptr _ | Seq _ | Exists _ | Extension _ -> None

