let bv_value n =
  let z =
    match int 6 with
    | 0 -> Z.zero
    | 1 -> Z.one
    | 2 -> Z.minus_one
    | 3 -> Z.shift_left Z.one (n - 1)
    | 4 -> Z.pred (Z.shift_left Z.one (n - 1))
    | _ -> Z.of_int (int (1 lsl min n 16))
  in
  Sv.BitVec.mk_masked n z

let float_value p =
  let open Sv.Float in
  match int 8 with
  | 0 -> zero p
  | 1 -> neg_zero p
  | 2 -> one p
  | 3 -> nan p
  | 4 -> infinity p
  | 5 -> neg_infinity p
  | _ -> mk_bits p (Z.of_int (int (1 lsl 16)))

let value : Sv.ty -> Sv.t = function
  | TBool -> Sv.Bool.of_bool (Random.State.bool rs)
  | TBitVector n -> bv_value n
  | TFloat p -> float_value p
  | _ -> assert false

(** A few variables per type, so that rules matching the same variable twice
    fire. *)
let var =
  let vars = Hashtbl.create 16 in
  fun ty ->
    let i = int 3 in
    match Hashtbl.find_opt vars (i, ty) with
    | Some v -> v
    | None ->
        let v = Sv.mk_var (Symex.Var.of_int (Hashtbl.length vars)) ty in
        Hashtbl.replace vars (i, ty) v;
        v

let random_ty () : Sv.ty =
  match int 10 with
  | 0 | 1 -> TBool
  | 2 -> TFloat (pick Svalue.FloatPrecision.[ F16; F32 ])
  | 3 -> TBitVector (pick [ 16; 32 ])
  | _ -> TBitVector (1 + int 8)

let checked () = { Svalue.signed = chance 0.5; unsigned = chance 0.5 }

let is_lit (v : Sv.t) =
  match v.node.kind with Bool _ | BitVec _ | Float _ -> true | _ -> false

(** A term of the same shape as [v], so that rules matching two similar terms
    fire: its operands may be swapped, a literal operand replaced, and a strict
    comparison made non-strict (or conversely). *)
let mutate (v : Sv.t) =
  match v.node.kind with
  | Binop (op, a, b) ->
      let op : Svalue.Binop.t =
        match op with
        | Lt s | Leq s -> pick Svalue.Binop.[ Lt s; Leq s ]
        | op -> op
      in
      let fresh x = if is_lit x then value (ty_of x) else x in
      let a, b = if chance 0.3 then (b, a) else (fresh a, fresh b) in
      if Sv.equal_ty (ty_of a) (ty_of b) || op = BvConcat then
        if chance 0.5 then Sv.(Binop (op, a, b) <| ty_of v)
        else Eval.eval_binop op a b
      else v
  | _ -> v

(** The state of a draw: the terms drawn so far, and the type of the bit-vectors
    that its comparisons compare. *)
type draw = { mutable pool : Sv.t list; cmp_ty : Sv.ty }

(** A term of type [ty], of depth at most [depth], built either raw or with the
    smart constructors. It is sometimes a term drawn before, so that rules
    matching a term twice fire. *)
let rec term d ty depth : Sv.t =
  match List.filter (fun v -> Sv.equal_ty (ty_of v) ty) d.pool with
  | _ :: _ as l when chance 0.25 -> pick l
  | _ :: _ as l when chance 0.25 -> mutate (pick l)
  | _ ->
      let v = fresh d ty depth in
      d.pool <- v :: d.pool;
      v

and fresh d ty depth =
  if depth = 0 || chance 0.4 then if chance 0.5 then value ty else var ty
  else
    let sub ty = term d ty (depth - 1) in
    let raw = chance 0.5 in
    let unop op a =
      if raw then Sv.(Unop (op, a) <| ty) else Eval.eval_unop op a
    in
    let binop op a b =
      if raw then Sv.(Binop (op, a, b) <| ty) else Eval.eval_binop op a b
    in
    (* the operands of a binary operator, often with a literal *)
    let operands ty =
      let a = sub ty in
      match int 3 with
      | 0 -> (a, sub ty)
      | 1 -> (a, value ty)
      | _ -> (value ty, a)
    in
    let ite () =
      let g = sub TBool in
      if raw then Sv.(Triop (Ite, g, sub ty, sub ty) <| ty)
      else Sv.Bool.ite g (sub ty) (sub ty)
    in
    match ty with
    | TBool -> (
        match int 7 with
        | 0 -> unop Not (sub TBool)
        | 1 -> binop (pick Svalue.Binop.[ And; Or ]) (sub TBool) (sub TBool)
        | 2 ->
            let t = if chance 0.7 then d.cmp_ty else random_ty () in
            binop Eq (sub t) (sub t)
        | 3 | 4 ->
            let t = d.cmp_ty in
            let op =
              pick
                Svalue.Binop.
                  [
                    Lt true;
                    Lt false;
                    Leq true;
                    Leq false;
                    AddOvf true;
                    AddOvf false;
                    SubOvf true;
                    SubOvf false;
                    MulOvf true;
                    MulOvf false;
                  ]
            in
            let a, b = operands t in
            binop op a b
        | 5 -> ite ()
        | _ -> fresh d ty 0)
    | TBitVector n -> (
        match int 9 with
        | 0 | 1 ->
            let op =
              pick
                Svalue.Binop.
                  [
                    Add (checked ());
                    Sub (checked ());
                    Mul (checked ());
                    Div (chance 0.5);
                    Rem (chance 0.5);
                    Mod;
                    BitAnd;
                    BitOr;
                    BitXor;
                    Shl;
                    LShr;
                    AShr;
                  ]
            in
            let a, b = operands ty in
            binop op a b
        | 2 -> unop (pick Svalue.Unop.[ BvNot; Neg (chance 0.5) ]) (sub ty)
        | 3 -> unop (BvOfBool n) (sub TBool)
        | 4 ->
            let k = int 4 in
            let i = int (k + 1) in
            unop (BvExtract (i, i + n - 1)) (sub (TBitVector (n + k)))
        | 5 when n > 1 ->
            let k = 1 + int (n - 1) in
            unop (BvExtend (chance 0.5, k)) (sub (TBitVector (n - k)))
        | 6 when n > 1 ->
            let k = 1 + int (n - 1) in
            binop BvConcat (sub (TBitVector k)) (sub (TBitVector (n - k)))
        | 7 -> ite ()
        | _ -> fresh d ty 0)
    | TFloat _ -> (
        match int 4 with
        | 0 -> unop (pick Svalue.Unop.[ FNeg; FAbs ]) (sub ty)
        | 1 -> binop FAdd (sub ty) (sub ty)
        | 2 -> ite ()
        | _ -> fresh d ty 0)
    | _ -> assert false

(** The arguments of one draw: most terms have the same type, so that the draw
    is likely to be well-typed. *)
let source () : Cases.source =
  let main = random_ty () in
  let depth = 2 in
  let cmp_ty : Sv.ty =
    match main with TBitVector _ -> main | _ -> TBitVector (1 + int 8)
  in
  let d = { pool = []; cmp_ty } in
  let any_term () =
    let ty = if chance 0.7 then main else random_ty () in
    term d ty depth
  in
  {
    int = (fun () -> Z.of_int (if chance 0.1 then pick [ 16; 32 ] else int 9));
    bool = (fun () -> Random.State.bool rs);
    term = any_term;
    terms = (fun () -> List.init (int 4) (fun _ -> term d main depth));
    choose = int;
  }

