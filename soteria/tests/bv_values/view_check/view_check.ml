  incr probe_n;
  (Types.node (Var (Var.of_int (1_000_000 + !probe_n))) TBool).tag

let kind_name (v : Types.t) =
  let first s = List.hd (String.split_on_char ' ' s) in
  match v.kind with
  | Var _ -> "Var"
  | Seq _ -> "Seq"
  | Bool _ -> "Bool"
  | Exists _ -> "Exists"
  | BitVec _ -> "BitVec"
  | LocLit _ -> "LocLit"
  | Float _ -> "Float"
  | Op1 (op, _) -> "op1:" ^ first (str Soteria.Bv_values.Lang.pp_op1 op)
  | Op2 (op, _, _) -> "op2:" ^ first (str Soteria.Bv_values.Lang.pp_op2 op)
  | Op3 (op, _, _, _) -> "op3:" ^ first (str Soteria.Bv_values.Lang.pp_op3 op)
  | OpN (op, _) -> "opN:" ^ first (str Soteria.Bv_values.Lang.pp_opn op)

