module Suite (K : K) = struct
  module L = Lang_make.Make (Types) (K)
  module G = Gen.Make (L.Svalue)

  (* the terms of the random generator, with their subterms *)
  let random_terms ~target : Types.t list =
    let seen = Hashtbl.create 4096 and acc = ref [] and n = ref 0 in
    let rec go (v : Types.t) =
      if not (Hashtbl.mem seen v.tag) then (
        Hashtbl.add seen v.tag ();
        incr n;
        List.iter go (K.operands v);
        acc := v :: !acc)
    in
    let seed = ref 0 in
    while !n < target do
      incr seed;
      let rng = Random.State.make [| !seed |] in
      for _ = 1 to 500 do
        let s = G.sorts.(Random.State.int rng (Array.length G.sorts)) in
        go (G.gen rng 5 s)
      done
    done;
    List.rev !acc

  let sorts : Types.ty list =
    [
      TBool;
      TBitVector 1;
      TBitVector 5;
      TBitVector 7;
      TBitVector 8;
      TBitVector 16;
      TBitVector 32;
      TBitVector 64;
      TFloat F16;
      TFloat F32;
      TFloat F64;
      TFloat F128;
      TLoc 16;
      TLoc 8;
      TPointer 16;
      TPointer 8;
      TSeq (TBitVector 8);
      TSeq TBool;
      TSeq (TSeq (TBitVector 8));
    ]

  (* raw terms (no simplification) of every node of the language, over operands
     of the right sorts taken in [pool] *)
  let raw_terms (pool : Types.ty -> Types.t array) : Types.t list =
    let rng = Random.State.make [| 4242 |] in
    let pick ty =
      let a = pool ty in
      a.(Random.State.int rng (Array.length a))
    in
    let n = ref [] in
    let add kind ty = n := Types.node kind ty :: !n in
    let bools = [ true; false ] in
    let checkeds =
      [
        { signed = false; unsigned = false };
        { signed = true; unsigned = true };
        { signed = true; unsigned = false };
        { signed = false; unsigned = true };
      ]
    in
    let rms : rm list =
      [ NearestTiesToEven; Truncate; Ceil; Floor; NearestTiesToAway ]
    in
    let fcs : fc list = [ Normal; Subnormal; Zero; Infinite; NaN ] in
    let fps : fp list = [ F16; F32; F64; F128 ] in
    let bv8 = TBitVector 8 and bv16 = TBitVector 16 and f32 = TFloat F32 in
    let reps = 4 in
    for _ = 1 to reps do
      (* leaves *)
      add (Var (Var.of_int (Random.State.int rng 5))) (pick TBool).ty;
      List.iter
        (fun ty -> add (Var (Var.of_int (20 + Random.State.int rng 5))) ty)
        sorts;
      List.iter
        (fun nb ->
          let lim = Z.shift_left Z.one nb in
          List.iter
            (fun z -> add (BitVec (Z.rem z lim)) (TBitVector nb))
            [ Z.zero; Z.one; Z.of_int 5; Z.pred lim; Z.of_int 0xf0 ];
          add (LocLit (Z.rem (Z.of_int 3) lim)) (TLoc nb))
        [ 1; 4; 5; 7; 8; 12; 16; 32; 64 ];
      add (Bool true) TBool;
      add (Bool false) TBool;
      List.iter
        (fun p ->
          add
            (Float (F.of_bits_z p (Z.of_int (Random.State.int rng 100000))))
            (TFloat p))
        fps;
      add (Seq []) (TSeq bv8);
      add (Seq [ pick bv8; pick bv8 ]) (TSeq bv8);
      add (Seq [ pick TBool ]) (TSeq TBool);
      add (Seq []) (TSeq (TSeq bv8));
      add
        (Exists ([ (Var.of_int 3, bv8); (Var.of_int 4, TBool) ], pick TBool))
        TBool;
      add (Exists ([], pick TBool)) TBool;
      (* op1 *)
      add (Op1 (Not, pick TBool)) TBool;
      add (Op1 (Not, pick TBool)) TBool;
      List.iter
        (fun () ->
          add (Op1 (BvOfBool 8, pick TBool)) bv8;
          add (Op1 (BvExtract (0, 3), pick bv8)) (TBitVector 4);
          List.iter (fun s -> add (Op1 (BvExtend (s, 8), pick bv8)) bv16) bools;
          add (Op1 (BvNot, pick bv8)) bv8;
          List.iter (fun c -> add (Op1 (Neg c, pick bv8)) bv8) bools;
          List.iter
            (fun rm ->
              List.iter
                (fun s ->
                  add (Op1 (BvOfFloat (rm, s, 16), pick f32)) bv16;
                  add (Op1 (FloatOfBv (rm, s, F32), pick bv16)) f32)
                bools;
              add (Op1 (FloatOfFloat (rm, F64), pick f32)) (TFloat F64);
              add (Op1 (FRound rm, pick f32)) f32)
            rms;
          add (Op1 (FloatOfBvRaw F32, pick (TBitVector 32))) f32;
          add (Op1 (FAbs, pick f32)) f32;
          add (Op1 (FNeg, pick f32)) f32;
          add (Op1 (FSqrt, pick f32)) f32;
          List.iter (fun fc -> add (Op1 (FIs fc, pick f32)) TBool) fcs;
          add (Op1 (FIsNeg, pick f32)) TBool;
          add (Op1 (FIsPos, pick f32)) TBool;
          add (Op1 (GetPtrLoc, pick (TPointer 16))) (TLoc 16);
          add (Op1 (GetPtrOfs, pick (TPointer 16))) bv16)
        [ () ];
      (* op2 *)
      add (Op2 (And, pick TBool, pick TBool)) TBool;
      add (Op2 (Or, pick TBool, pick TBool)) TBool;
      List.iter
        (fun ty ->
          add (Op2 (Eq, pick ty, pick ty)) TBool;
          add (Op1 (Not, Types.node (Op2 (Eq, pick ty, pick ty)) TBool)) TBool)
        sorts;
      List.iter
        (fun c ->
          add (Op2 (Add c, pick bv8, pick bv8)) bv8;
          add (Op2 (Sub c, pick bv8, pick bv8)) bv8;
          add (Op2 (Mul c, pick bv8, pick bv8)) bv8)
        checkeds;
      List.iter
        (fun s ->
          add (Op2 (Div s, pick bv8, pick bv8)) bv8;
          add (Op2 (Rem s, pick bv8, pick bv8)) bv8;
          add (Op2 (AddOvf s, pick bv8, pick bv8)) TBool;
          add (Op2 (SubOvf s, pick bv8, pick bv8)) TBool;
          add (Op2 (MulOvf s, pick bv8, pick bv8)) TBool;
          add (Op2 (Lt s, pick bv8, pick bv8)) TBool;
          add (Op2 (Leq s, pick bv8, pick bv8)) TBool)
        bools;
      add (Op2 (Mod, pick bv8, pick bv8)) bv8;
      add (Op2 (BvConcat, pick bv8, pick bv8)) bv16;
      add (Op2 (BitAnd, pick bv8, pick bv8)) bv8;
      add (Op2 (BitOr, pick bv8, pick bv8)) bv8;
      add (Op2 (BitXor, pick bv8, pick bv8)) bv8;
      add (Op2 (Shl, pick bv8, pick bv8)) bv8;
      add (Op2 (LShr, pick bv8, pick bv8)) bv8;
      add (Op2 (AShr, pick bv8, pick bv8)) bv8;
      add (Op2 (FEq, pick f32, pick f32)) TBool;
      add (Op2 (FLeq, pick f32, pick f32)) TBool;
      add (Op2 (FLt, pick f32, pick f32)) TBool;
      List.iter
        (fun op -> add (Op2 (op, pick f32, pick f32)) f32)
        [ FAdd; FSub; FMul; FDiv; FRem; FMin; FMax ];
      add (Op2 (Ptr, pick (TLoc 16), pick bv16)) (TPointer 16);
      add (Op2 (Ptr, pick (TLoc 8), pick bv8)) (TPointer 8);
      (* op3, opN *)
      List.iter
        (fun ty -> add (Op3 (Ite, pick TBool, pick ty, pick ty)) ty)
        sorts;
      add (Op3 (Fma, pick f32, pick f32, pick f32)) f32;
      add (OpN (Distinct, [ pick bv8; pick bv8; pick bv8 ])) TBool;
      add (OpN (Distinct, [])) TBool;
      add (OpN (Distinct, [ pick bv8 ])) TBool
    done;
    (* contiguous and non contiguous variables, for [Distinct] *)
    let v k = Types.node (Var (Var.of_int k)) bv8 in
    List.iter
      (fun l -> add (OpN (Distinct, List.map v l)) TBool)
      [
        [ 1; 2; 3 ];
        [ 3; 1; 2 ];
        [ 1; 3 ];
        [ 5 ];
        [ 1; 1; 3 ];
        [ 0; 1 ];
        [ 7; 9; 8; 10 ];
      ];
    add (OpN (Distinct, [ v 1; pick bv8; v 3 ])) TBool;
    (* the shapes of [as_range], and of the [Eq]/[Lt]/[Leq] pairs of
       [implies_or_contradicts], both orders of everything *)
    List.iter
      (fun w ->
        let ty = TBitVector w in
        let lim = Z.shift_left Z.one w in
        let x = Types.node (Var (Var.of_int 1)) ty in
        let y = Types.node (Var (Var.of_int 2)) ty in
        let lit z = Types.node (BitVec (Z.rem (Z.add z lim) lim)) ty in
        let half = Z.shift_left Z.one (w - 1) in
        let zl =
          [
            Z.zero;
            Z.one;
            Z.of_int 5;
            Z.pred half;
            half;
            Z.succ half;
            Z.pred lim;
            Z.pred (Z.pred lim);
            Z.of_int 100;
          ]
        in
        let addc c a b = Types.node (Op2 (Add c, a, b)) ty in
        let cs = List.nth checkeds 0 in
        List.iter
          (fun c1 ->
            List.iter
              (fun c2 ->
                let shapes_lhs =
                  [
                    x;
                    addc cs x (lit c2);
                    addc cs (lit c2) x;
                    addc cs y (lit c2);
                    addc cs (lit c2) (lit c1);
                    Types.node (Op2 (Sub cs, x, lit c2)) ty;
                  ]
                in
                List.iter
                  (fun s ->
                    List.iter
                      (fun strict ->
                        let op = if strict then Lt s else Leq s in
                        List.iter
                          (fun sh ->
                            let mk a b =
                              let t = Types.node (Op2 (op, a, b)) TBool in
                              add t.kind TBool;
                              add (Op1 (Not, t)) TBool
                            in
                            mk (lit c1) sh;
                            mk sh (lit c1);
                            mk x (lit c1);
                            mk (lit c1) x;
                            mk x y)
                          shapes_lhs)
                      bools)
                  bools)
              zl;
            let e a b = Types.node (Op2 (Eq, a, b)) TBool in
            add (e (lit c1) x).kind TBool;
            add (e x (lit c1)).kind TBool;
            add (Op1 (Not, e (lit c1) x)) TBool;
            add (Op1 (Not, e x (lit c1))) TBool;
            add (e (lit c1) y).kind TBool;
            add (e x y).kind TBool;
            add (e y x).kind TBool;
            add (Op1 (Not, e x y)) TBool;
            add (Op1 (Not, e y x)) TBool;
            add (Op1 (Not, Types.node (Op1 (Not, e x (lit c1))) TBool)) TBool)
          zl;
        (* [Eq] with a literal at a location sort *)
        add
          (Op2
             ( Eq,
               Types.node (LocLit Z.zero) (TLoc w),
               Types.node (Var (Var.of_int 9)) (TLoc w) ))
          TBool)
      [ 8; 16; 32 ];
    List.rev !n

  (* the terms of every sort, to build the other arguments *)
  let pools (terms : Types.t list) : Types.ty -> Types.t array =
    let h : (Types.ty, Types.t list) Hashtbl.t = Hashtbl.create 16 in
    List.iter
      (fun (v : Types.t) ->
        Hashtbl.replace h v.ty
          (v :: Option.value ~default:[] (Hashtbl.find_opt h v.ty)))
      terms;
    let cache = Hashtbl.create 16 in
    fun ty ->
      match Hashtbl.find_opt cache ty with
      | Some a -> a
      | None ->
          let l = Option.value ~default:[] (Hashtbl.find_opt h ty) in
          let a =
            match l with
            | [] -> [| Types.node (Var (Var.of_int 77)) ty |]
            | l -> Array.of_list l
          in
          Hashtbl.add cache ty a;
          a

  (* {2 The calls} *)

  (* a result, or the exception that the call raised *)
  let run (f : unit -> string) : string =
    try f () with
    | Failure m -> "Failure " ^ m
    | Assert_failure _ -> "Assert_failure"
    | Invalid_argument m -> "Invalid_argument " ^ m
    | Not_found -> "Not_found"
    | Division_by_zero -> "Division_by_zero"

  let tm = tg

  (* every function of one term; the pairs are (function, result) *)
  let on_term (v : Types.t) : (string * string) list =
    let one name f = (name, run f) in
    [
      one "is_literal" (fun () -> string_of_bool (K.is_literal v));
      one "as_var" (fun () ->
          opt (fun x -> string_of_int (Var.to_int x)) (K.as_var v));
      one "as_not" (fun () -> opt tm (K.as_not v));
      one "as_eq" (fun () -> opt (pair tm tm) (K.as_eq v));
      one "as_and" (fun () -> opt (pair tm tm) (K.as_and v));
      one "as_or" (fun () -> opt (pair tm tm) (K.as_or v));
      one "as_ite" (fun () ->
          opt (fun (a, b, c) -> tm a ^ tm b ^ tm c) (K.as_ite v));
      one "as_lt" (fun () ->
          opt (fun (s, a, b) -> string_of_bool s ^ tm a ^ tm b) (K.as_lt v));
      one "as_leq" (fun () ->
          opt (fun (s, a, b) -> string_of_bool s ^ tm a ^ tm b) (K.as_leq v));
      one "as_distinct" (fun () -> opt (lst tm) (K.as_distinct v));
      one "as_exists" (fun () ->
          opt
            (pair (lst (pair (fun x -> string_of_int (Var.to_int x)) sty)) tm)
            (K.as_exists v));
      one "as_ptr" (fun () -> opt (pair tm tm) (K.as_ptr v));
      one "as_bv_lit" (fun () -> opt zs (K.as_bv_lit v));
      one "as_loc_lit" (fun () -> opt zs (K.as_loc_lit v));
      one "as_float_lit" (fun () ->
          opt (fun f -> F.to_string f ^ "/" ^ zs (F.to_z f)) (K.as_float_lit v));
      one "conjuncts" (fun () -> lst tm (K.conjuncts v));
      one "as_range" (fun () -> show_range (K.as_range v));
      one "operands" (fun () -> lst tm (K.operands v));
      one "rebuild(operands)" (fun () ->
          let r = K.rebuild v (K.operands v) in
          if r != v then "DIFFERENT " ^ nt r else "same");
      one "maps_operands" (fun () -> string_of_bool (K.maps_operands v));
      one "cost" (fun () -> zs (K.cost v));
      one "encode_head" (fun () ->
          apply_op ~pp_ty:sty (K.encode_head v) (K.operands v));
      one "learn_alts" (fun () -> show_plan (K.learn_alts v));
      (* the sort of the term *)
      one "sized_ty" (fun () -> opt zs (K.sized_ty v.ty));
      one "as_bv_ty" (fun () -> opt zs (K.as_bv_ty v.ty));
      one "as_float_ty" (fun () ->
          opt
            (fun p -> string_of_int (Floatml.AnyFloat.size p))
            (K.as_float_ty v.ty));
      one "as_seq_ty" (fun () -> opt sty (K.as_seq_ty v.ty));
      one "is_bool_ty" (fun () -> string_of_bool (K.is_bool_ty v.ty));
      one "sort_operands" (fun () -> lst sty (K.sort_operands v.ty));
      one "encode_sort" (fun () ->
          let log = Buffer.create 16 in
          let sort_of_ty ty =
            Buffer.add_string log ("s" ^ sty ty ^ ";");
            Smt.atom ("s" ^ sty ty)
          in
          let r =
            match
              collect
                (fun () ->
                  K.encode_sort v.ty ~sort_of_ty (K.sort_operands v.ty))
                log
            with
            | s -> str Smt.pp_sexp s
            | exception Failure m -> "failure " ^ m
          in
          Buffer.contents log ^ r);
      one "random_bound" (fun () -> opt zs (K.random_bound v.ty));
    ]

  (* the inputs that are not a term: a sort and a number, widths, pairs *)
  let on_sort_z (ty : Types.ty) (z : Z.t) : (string * string) list =
    [
      ( "random_of_z",
        run (fun () ->
            match K.random_of_z ty z with
            | None -> "None"
            | Some v -> "Some " ^ nt v) );
    ]

  let on_width (n : Z.t) : (string * string) list =
    [
      ("t_bool", run (fun () -> sty K.t_bool));
      ("t_bv", run (fun () -> sty (K.t_bv n)));
      ("t_loc", run (fun () -> sty (K.t_loc n)));
      ("t_ptr", run (fun () -> sty (K.t_ptr n)));
      ("t_float", run (fun () -> sty (K.t_float F32)));
      ("t_seq", run (fun () -> sty (K.t_seq (K.t_bv n))));
    ]

  let on_pair (q : Types.t) (pc : Types.t) : (string * string) list =
    [
      ( "implies_or_contradicts",
        run (fun () ->
            opt string_of_bool (K.implies_or_contradicts q (K.b_not q) pc)) );
    ]

  (* rebuild with other operands of the same sorts, a wrong number of
     operands *)
  let on_rebuild pool (v : Types.t) k : (string * string) list =
    let cs = K.operands v in
    let n = List.length cs in
    let pick ty =
      let a = pool ty in
      a.(k mod Array.length a)
    in
    let variants =
      List.init n (fun j ->
          List.mapi (fun i (c : Types.t) -> if i = j then pick c.ty else c) cs)
      @ [ (match cs with [] -> [ v ] | _ :: rest -> rest); cs @ cs ]
    in
    List.mapi
      (fun i cs' ->
        ("rebuild", run (fun () -> nt (K.rebuild v cs')) ^ " " ^ string_of_int i))
      variants

  let on_learn pool (e : Types.t) k : (string * string) list =
    let w = match e.ty with TBitVector w -> Some w | _ -> None in
    let target : Types.t =
      match (k mod 3, e.ty) with
      | 0, TBitVector w -> K.mk_masked w (Z.of_int (k mod 256))
      | 1, TBitVector w when w >= 1 -> K.mk_masked w (Z.of_int (k land 1))
      | 0, TBool -> K.v_true
      | _, TPointer w ->
          K.mk_ptr (K.mk_loc w (Z.of_int 3)) (K.mk_bv w (Z.of_int 4))
      | _ ->
          let a = pool e.ty in
          a.(k mod Array.length a)
    in
    ignore w;
    ("learn_target", nt target)
    :: List.map
         (fun i ->
           ( "learn_value",
             run (fun () -> opt nt (K.learn_value e (Z.of_int i) target))
             ^ " "
             ^ string_of_int i ))
         [ 0; 1; 2 ]
end

