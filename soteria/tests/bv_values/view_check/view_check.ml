(* {1 The encoding, with the order of its calls} *)

let rec collect : 'a. (unit -> 'a) -> Buffer.t -> 'a =
 fun f log ->
  try f ()
  with effect Decls.Declare d, k ->
    Buffer.add_string log (Printf.sprintf "decl key=%s;" d.key);
    let cmds = ref [] in
    collect (fun () -> d.commands (fun s -> cmds := s :: !cmds)) log;
    List.iter
      (fun s -> Buffer.add_string log (str Smt.pp_sexp s ^ ";"))
      (List.rev !cmds);
    Effect.Deep.continue k ()

(* the sexp that an operator builds from placeholders for its operands and
   sorts, and the order in which it asked for them *)
let apply_op ~(pp_ty : ty -> string) op operands =
  let log = Buffer.create 64 in
  let encode_child (c : Types.t) =
    Buffer.add_string log (Printf.sprintf "c%d;" c.tag);
    Smt.atom (Printf.sprintf "c%d" c.tag)
  in
  let sort_of_ty (ty : ty) =
    Buffer.add_string log (Printf.sprintf "s%s;" (pp_ty ty));
    Smt.atom ("s" ^ pp_ty ty)
  in
  let r =
    match collect (fun () -> op ~sort_of_ty ~encode_child operands) log with
    | s -> str Smt.pp_sexp s
    | exception Failure m -> "failure " ^ m
  in
  Buffer.contents log ^ r

