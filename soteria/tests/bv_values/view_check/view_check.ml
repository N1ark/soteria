(* {1 Printing of results} *)

let tg (v : Types.t) = Printf.sprintf "#%d" v.tag
let opt f = function None -> "None" | Some x -> "Some(" ^ f x ^ ")"
let lst f l = "[" ^ String.concat ";" (List.map f l) ^ "]"
let pair f g (a, b) = "(" ^ f a ^ "," ^ g b ^ ")"
let zs = Z.to_string
let str pp x = Format.asprintf "%a" pp x

let show_plan : View_host.learn_plan -> string = function
  | LNone -> "LNone"
  | LAlts l -> "LAlts" ^ lst (pair zs zs) l
  | LAll (e, o) -> "LAll" ^ pair (lst zs) (lst zs) (e, o)

let show_range =
  opt (fun (x, size, (side, (lo, hi))) ->
      Printf.sprintf "%d,%s,%s,%s,%s" (Var.to_int x) (zs size)
        (match side with View_host.Inside -> "In" | Outside -> "Out")
        (zs lo) (zs hi))

(* The terms that a call creates are compared by structure, with the operands of
   the commutative operators sorted: the weak table of the nodes may drop a node
   and create it again, with another tag, between the two runs. The order of
   creation is compared by [creation_trials], on terms that no table knows. *)

let canon (v : Types.t) : string =
  let comm = function
    | And | Or | Eq | Add _ | Mul _ | AddOvf _ | MulOvf _ | BitAnd | BitOr
    | BitXor | FEq ->
        true
    | _ -> false
  in
  let ty_s ty = Format.asprintf "%a" Kanon_ref.pp_ty ty in
  let rec go (v : Types.t) : string =
    match v.kind with
    | Var x -> Printf.sprintf "(var %d : %s)" (Var.to_int x) (ty_s v.ty)
    | Seq l ->
        Printf.sprintf "(seq : %s %s)" (ty_s v.ty)
          (String.concat " " (List.map go l))
    | Bool x -> string_of_bool x
    | BitVec z -> Printf.sprintf "(bv %s : %s)" (Z.to_string z) (ty_s v.ty)
    | LocLit z -> Printf.sprintf "(loc %s : %s)" (Z.to_string z) (ty_s v.ty)
    | Float f ->
        Printf.sprintf "(float %s/%s)" (F.to_string f) (Z.to_string (F.to_z f))
    | Exists (bs, body) ->
        Printf.sprintf "(exists %s %s)"
          (String.concat ","
             (List.map
                (fun (x, ty) -> Printf.sprintf "%d:%s" (Var.to_int x) (ty_s ty))
                bs))
          (go body)
    | Op1 (op, a) ->
        Printf.sprintf "(%s %s)"
          (Format.asprintf "%a" Soteria.Bv_values.Lang.pp_op1 op)
          (go a)
    | Op2 (op, x, y) ->
        let l = [ go x; go y ] in
        let l = if comm op then List.sort compare l else l in
        Printf.sprintf "(%s %s)"
          (Format.asprintf "%a" Soteria.Bv_values.Lang.pp_op2 op)
          (String.concat " " l)
    | Op3 (op, x, y, z) ->
        Printf.sprintf "(%s %s %s %s)"
          (Format.asprintf "%a" Soteria.Bv_values.Lang.pp_op3 op)
          (go x) (go y) (go z)
    | OpN (op, l) ->
        Printf.sprintf "(%s %s)"
          (Format.asprintf "%a" Soteria.Bv_values.Lang.pp_opn op)
          (String.concat " " (List.sort compare (List.map go l)))
  in
  go v

(* a term that a call created *)
let nt (v : Types.t) = canon v

