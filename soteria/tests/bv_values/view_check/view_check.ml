(* Differential test of the view functions generated by Kanon ([rules/view.kn],
   through {!Kanon_gen}) against the hand-written reference ({!Kanon_ref}).

   [view_check check]: for every view function, on at least [VIEW_CHECK_TERMS]
   terms (default 200000) of the corpus of [iface/check] (random terms built
   through the smart constructors) and on raw terms of every node kind, the two
   implementations give the same result; the functions that create nodes
   ([rebuild], [learn_value]) are also compared on the nodes they create, and
   their order (see [creation_trials]). Also: [rebuild v (operands v) == v], and
   every node kind occurs. *)

