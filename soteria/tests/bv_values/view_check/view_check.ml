let env_int name default =
  match Sys.getenv_opt name with Some s -> int_of_string s | None -> default

let target = env_int "VIEW_CHECK_TERMS" 200000
let n_trials = env_int "VIEW_CHECK_TRIALS" 20000

module SR = Suite (Kref)
module SG = Suite (Kgen)

type corpus = { random : Types.t list; all : Types.t list }

(* the generator draws fresh variables, so it is not reproducible in the same
   process: the two implementations share one corpus *)
let build_corpus () : corpus =
  let random = SG.random_terms ~target in
  let raw = SG.raw_terms (SG.pools random) in
  { random; all = random @ raw }

let diffs = ref 0
let cases = ref 0
let per_fn : (string, int) Hashtbl.t = Hashtbl.create 64

(* the calls whose result is not [None], [false], [[]], an exception... *)
let nontrivial : (string, int) Hashtbl.t = Hashtbl.create 64

(* compare the results of the two implementations on one input, [ctx] says
   which *)
let compare_results ~(ctx : unit -> string) (a : (string * string) list)
    (b : (string * string) list) =
  List.iter2
    (fun (n, r) (n', r') ->
      assert (n = n');
      incr cases;
      Hashtbl.replace per_fn n
        (1 + Option.value ~default:0 (Hashtbl.find_opt per_fn n));
      if not (List.mem r [ "None"; "false"; "[]"; "same" ]) then
        Hashtbl.replace nontrivial n
          (1 + Option.value ~default:0 (Hashtbl.find_opt nontrivial n));
      if r <> r' then (
        incr diffs;
        if !diffs <= 20 then
          Printf.printf "DIFF %s on %s:\n  generated: %s\n  reference: %s\n%!" n
            (ctx ()) r r'))
    a b

(* [rebuild v (operands v) == v] for the terms built by the smart constructors
   (the raw terms of the corpus are not normal forms). Two exceptions, both in
   the rules and not in the view functions (found by this test, and also in the
   old code, which has the same rules): - [b_distinct] stops its check at the
   first pair that is not surely different, so [distinct x y x] is a normal
   form, which is sorted to [distinct x x y] and then simplified to [false] by a
   second call; - [bv_lt_zero] builds [Lt (true, v, 0)] without looking at [v]:
   with a literal [v] the result is a comparison of literals, which [bv_lt]
   folds. *)
let rebuild_bad = ref 0
let rebuild_distinct_dups = ref 0
let rebuild_lit_cmp = ref 0

let has_duplicates (l : Types.t list) =
  let tags = List.map (fun (v : Types.t) -> v.tag) l in
  List.length (List.sort_uniq Int.compare tags) <> List.length tags

let compare_all (c : corpus) =
  let pool = SG.pools c.all in
  let counts = Hashtbl.create 64 in
  List.iter
    (fun (v : Types.t) ->
      if Kgen.rebuild v (Kgen.operands v) != v then
        match v.kind with
        | OpN (Distinct, l) when has_duplicates l -> incr rebuild_distinct_dups
        | Op2 ((Lt _ | Leq _), a, b) when Kgen.is_literal a && Kgen.is_literal b
          ->
            incr rebuild_lit_cmp
        | _ ->
            incr rebuild_bad;
            if !rebuild_bad <= 5 then
              Printf.printf "rebuild (operands v) <> v on %s\n%!"
                (Soteria.Bv_values.Lang.show v))
    c.random;
  let rng = Random.State.make [| 7 |] in
  let arr = Array.of_list c.all in
  let n = Array.length arr in
  List.iteri
    (fun k (v : Types.t) ->
      let kn = kind_name v in
      Hashtbl.replace counts kn
        (1 + Option.value ~default:0 (Hashtbl.find_opt counts kn));
      let ctx () = Soteria.Bv_values.Lang.show v in
      compare_results ~ctx (SG.on_term v) (SR.on_term v);
      compare_results ~ctx (SG.on_rebuild pool v k) (SR.on_rebuild pool v k);
      compare_results ~ctx (SG.on_learn pool v k) (SR.on_learn pool v k);
      (* a pair: the term with a random one *)
      (* the pairs that the function decides: the comparisons of the same
         operands, in either order, with either flag *)
      (match (Kref.as_lt v, Kref.as_leq v, Kref.as_eq v, Kref.as_not v) with
      | Some (_, a, b), _, _, _
      | _, Some (_, a, b), _, _
      | _, _, Some (a, b), _
      | _, _, _, Some { kind = Op2 (Eq, a, b); _ } ->
          List.iter
            (fun pc ->
              let ctx () =
                Soteria.Bv_values.Lang.show v
                ^ "  and  "
                ^ Soteria.Bv_values.Lang.show pc
              in
              compare_results ~ctx (SG.on_pair v pc) (SR.on_pair v pc);
              compare_results ~ctx (SG.on_pair pc v) (SR.on_pair pc v))
            (List.concat_map
               (fun (x, y) ->
                 List.concat_map
                   (fun s ->
                     [
                       Types.node (Op2 (Lt s, x, y)) TBool;
                       Types.node (Op2 (Leq s, x, y)) TBool;
                     ])
                   [ true; false ]
                 @ [ Types.node (Op2 (Eq, x, y)) TBool ])
               [ (a, b); (b, a) ])
      | _ -> ());
      if v.ty = TBool then
        for _ = 1 to 3 do
          let other = arr.(Random.State.int rng n) in
          if other.ty = TBool then (
            let ctx () =
              Soteria.Bv_values.Lang.show v
              ^ "  and  "
              ^ Soteria.Bv_values.Lang.show other
            in
            compare_results ~ctx (SG.on_pair v other) (SR.on_pair v other);
            compare_results ~ctx (SG.on_pair other v) (SR.on_pair other v))
        done)
    c.all;
  (* the sorts, and numbers: the random values of every sort, and widths *)
  let n_z = (target / 12) + 1 in
  List.iter
    (fun ty ->
      let zs =
        match Kref.random_bound ty with
        | None -> [ Z.zero; Z.one ]
        | Some b ->
            Z.zero
            :: Z.one
            :: Z.pred b
            :: List.init n_z (fun _ ->
                Z.rem
                  (Z.random_bits 40
                  |> Z.mul (Z.of_int (Random.State.int rng 1000)))
                  b)
      in
      List.iter
        (fun z ->
          compare_results
            ~ctx:(fun () -> Printf.sprintf "%s %s" (sty ty) (zs_ z))
            (SG.on_sort_z ty z) (SR.on_sort_z ty z))
        zs)
    SG.sorts;
  for n = 0 to target - 1 do
    compare_results
      ~ctx:(fun () -> string_of_int n)
      (SG.on_width (Z.of_int n))
      (SR.on_width (Z.of_int n))
  done;
  counts

(* {2 The order of node creation}

   The weak table of the nodes may drop a node and create it again with another
   tag, so tags cannot be compared between two runs on the same terms. Instead,
   for a call [f x]: build three copies of [x] with fresh variables (nodes that
   no table knows; same structure, same order of creation), run the call on the
   first as a warm-up (it creates the constants that the call creates), then the
   reference on the second and the generated function on the third. The two must
   create the same number of nodes, and the nodes of the result must have the
   same tags relative to the tag counter at the start of the call (so the same
   creation order). Then the roles are swapped, with the generated function in
   the warm-up. No GC runs during a trial. *)

(* [terms] with their variables renamed to fresh ones (raw nodes: no rule) *)
let fresh_base = ref 10_000_000

let rename (terms : Types.t list) : Types.t list =
  let vars = Hashtbl.create 16 and memo = Hashtbl.create 64 in
  let base = !fresh_base in
  let fresh x =
    match Hashtbl.find_opt vars (Var.to_int x) with
    | Some y -> y
    | None ->
        let y = Var.of_int (base + Hashtbl.length vars) in
        Hashtbl.add vars (Var.to_int x) y;
        y
  in
  let rec go (v : Types.t) : Types.t =
    match Hashtbl.find_opt memo v.tag with
    | Some r -> r
    | None ->
        let kind =
          match v.kind with
          | Var x -> Var (fresh x)
          | Seq l -> Seq (List.map go l)
          | (Bool _ | BitVec _ | LocLit _ | Float _) as k -> k
          | Exists (bs, b) ->
              let bs = List.map (fun (x, ty) -> (fresh x, ty)) bs in
              Exists (bs, go b)
          | Op1 (op, a) -> Op1 (op, go a)
          | Op2 (op, a, b) ->
              let a = go a in
              Op2 (op, a, go b)
          | Op3 (op, a, b, c) ->
              let a = go a in
              let b = go b in
              Op3 (op, a, b, go c)
          | OpN (op, l) -> OpN (op, List.map go l)
        in
        let r = Types.node kind v.ty in
        Hashtbl.add memo v.tag r;
        r
  in
  let r = List.map go terms in
  fresh_base := base + 1000;
  r

(* the tags, relative to [p0], of the nodes of [r] that the call created, in a
   traversal of [r] *)
let created_ranks ~p0 ~p1 (r : Types.t) : int list =
  let seen = Hashtbl.create 16 in
  let acc = ref [] in
  let rec go (v : Types.t) =
    if not (Hashtbl.mem seen v.tag) then (
      Hashtbl.add seen v.tag ();
      if v.tag > p0 && v.tag < p1 then acc := (v.tag - p0) :: !acc;
      List.iter go (Kref.operands v))
  in
  go r;
  List.rev !acc

let trial_diffs = ref 0
let trials = ref 0

let measure (f : unit -> Types.t) : string =
  let p0 = probe () in
  let r = try Ok (f ()) with e -> Error (Printexc.to_string e) in
  let p1 = probe () in
  match r with
  | Error e -> Printf.sprintf "%d nodes created, raised %s" (p1 - p0 - 1) e
  | Ok r ->
      Printf.sprintf "%d nodes created, ranks %s"
        (p1 - p0 - 1)
        (String.concat "," (List.map string_of_int (created_ranks ~p0 ~p1 r)))

(* [f_ref] and [f_gen] apply the reference and the generated function to the
   renamed copy of [inputs] *)
let trial name (inputs : Types.t list) f_ref f_gen =
  let swap = ref false in
  for _ = 1 to 2 do
    let w, a, b =
      if !swap then (f_gen, f_gen, f_ref) else (f_ref, f_ref, f_gen)
    in
    let c0 = rename inputs in
    let c1 = rename inputs in
    let c2 = rename inputs in
    Gc.minor ();
    (try ignore (w c0) with _ -> ());
    let ra = measure (fun () -> a c1) in
    let rb = measure (fun () -> b c2) in
    incr trials;
    if ra <> rb then (
      incr trial_diffs;
      if !trial_diffs <= 10 then
        Printf.printf
          "CREATION DIFF %s on %s (%s first):\n  first:  %s\n  second: %s\n%!"
          name
          (String.concat " ; " (List.map Soteria.Bv_values.Lang.show inputs))
          (if !swap then "generated" else "reference")
          ra rb);
    swap := true
  done

let creation_trials (c : corpus) =
  let pool = SG.pools c.all in
  let arr = Array.of_list c.all in
  let n = Array.length arr in
  let rng = Random.State.make [| 99 |] in
  let count = ref 0 in
  while !count < n_trials do
    incr count;
    let v = arr.(Random.State.int rng n) in
    let cs = Kref.operands v in
    (* rebuild with the operands, one of them replaced by another term of its
       sort *)
    (match cs with
    | [] -> ()
    | _ ->
        let j = Random.State.int rng (List.length cs) in
        let cs' =
          List.mapi
            (fun i (c : Types.t) ->
              if i = j then
                let p = pool c.ty in
                p.(Random.State.int rng (Array.length p))
              else c)
            cs
        in
        trial "rebuild" (v :: cs')
          (fun l -> Kref.rebuild (List.hd l) (List.tl l))
          (fun l -> Kgen.rebuild (List.hd l) (List.tl l)));
    (* learn_value, with a target of the sort of the term *)
    let target : Types.t =
      match v.ty with
      | TBitVector w -> Kref.mk_masked w (Z.of_int (Random.State.int rng 256))
      | TBool -> Kref.v_true
      | _ ->
          let p = pool v.ty in
          p.(Random.State.int rng (Array.length p))
    in
    for i = 0 to 1 do
      let get f = function
        | [ e; t ] -> (
            match f e (Z.of_int i) t with
            | Some r -> r
            | None -> Types.node (Bool true) TBool)
        | _ -> assert false
      in
      trial "learn_value" [ v; target ] (get Kref.learn_value)
        (get Kgen.learn_value)
    done
  done

let check () =
  Gc.set { (Gc.get ()) with minor_heap_size = 1 lsl 25 };
  let corpus = build_corpus () in
  let counts = compare_all corpus in
  let total = List.length corpus.all in
  let nrandom = List.length corpus.random in
  Printf.printf "terms: %d (%d random, %d raw)\n" total nrandom (total - nrandom);
  Printf.printf "calls compared: %d\n" !cases;
  Printf.printf "per function (calls):\n";
  Hashtbl.fold (fun k v acc -> (k, v) :: acc) per_fn []
  |> List.sort compare
  |> List.iter (fun (k, v) ->
      Printf.printf "  %-24s %-8d (%d not None/false/[])\n" k v
        (Option.value ~default:0 (Hashtbl.find_opt nontrivial k)));
  Printf.printf "node kinds in the corpus (every kind must occur):\n";
  let missing = ref [] in
  List.iter
    (fun k ->
      let c = Option.value ~default:0 (Hashtbl.find_opt counts k) in
      if c = 0 then missing := k :: !missing;
      Printf.printf "  %-14s %d\n" k c)
    all_kinds;
  let unknown =
    Hashtbl.fold
      (fun k _ acc -> if List.mem k all_kinds then acc else k :: acc)
      counts []
  in
  Printf.printf
    "rebuild v (operands v) == v: %d random terms, %d failures (and %d \
     distinct with a repeated operand, %d comparisons of literals: rules that \
     are not idempotent)\n"
    nrandom !rebuild_bad !rebuild_distinct_dups !rebuild_lit_cmp;
  Printf.printf "differences: %d\n%!" !diffs;
  creation_trials corpus;
  Printf.printf "creation order: %d trials, %d differences\n" !trials
    !trial_diffs;
  if !missing <> [] then (
    Printf.printf "MISSING KINDS: %s\n" (String.concat " " !missing);
    exit 1);
  if unknown <> [] then (
    Printf.printf "UNKNOWN KINDS: %s\n" (String.concat " " unknown);
    exit 1);
  if !diffs > 0 || !trial_diffs > 0 || !rebuild_bad > 0 then exit 1

let () = check ()
